import json
import sys
from pathlib import Path
from typing import Any

import mujoco
import numpy as np

from myo_sim.build.hand_data import fold_node_forces

ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = ROOT / "myo_sim" / "build" / "data" / "hand_literature.json"
WIKI_PATH = ROOT / "docs" / "wiki" / "hand-literature-comparison.md"
BEGIN = "<!-- BEGIN generated by scripts/hand_literature_comparison.py; do not edit by hand -->"
END = "<!-- END generated -->"
DIGITS = (2, 3, 4, 5)
# Distal-phalanx body of each digit (the thumb last).
DISTAL_BODIES = {**{d: f"distph{d}_r" for d in DIGITS}, "thumb": "distal_thumb_r"}
# Long flexor of each digit: its shortening defines the palmar side.
LONG_FLEXORS = {**{d: f"FDP{d}_r" for d in DIGITS}, "thumb": "FPL_r"}
PALM_PADS = ("palm_pad_r", "thenar_pad_r", "hypothenar_pad_r")
METACARPAL_BODIES = ("firstmc_r", "secondmc_r", "thirdmc_r", "fourthmc_r", "fifthmc_r")
FIST_SECONDS = 1.0


def load_data(path: Path = DATA_PATH) -> dict[str, Any]:
    return json.loads(path.read_text())


def _pads() -> Any:
    return _load_script("fit_hand_pads")


def _validator() -> Any:
    return _load_script("validate_hand_function")


def _load_script(name: str) -> Any:
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, Path(__file__).with_name(f"{name}.py"))
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module  # dataclasses resolve their module
    spec.loader.exec_module(module)
    return module


# --- geometry ---------------------------------------------------------------------------------------------


def _body_geoms(model: mujoco.MjModel, body: str) -> list[int]:
    b = model.body(body).id
    return [g for g in range(model.ngeom) if model.geom_bodyid[g] == b]


def _collision(model: mujoco.MjModel, g: int) -> bool:
    return model.geom_group[g] == 4 and model.geom_type[g] != mujoco.mjtGeom.mjGEOM_MESH


def fingertip_pads(model: mujoco.MjModel) -> dict[str, float]:
    """Fingertip soft tissue (Dallard 2018's D_N0) of digits 2-5 and the thumb at q = 0."""
    data = mujoco.MjData(model)
    mujoco.mj_forward(model, data)
    pads = _pads()
    corner = pads.load_table()["fingertip"]["corner_m"]
    return {
        str(digit): pads.fingertip_soft_tissue_mm(model, data, body, LONG_FLEXORS[digit], corner)
        for digit, body in DISTAL_BODIES.items()
    }


def palm_pads(model: mujoco.MjModel) -> dict[str, float]:
    """Soft tissue under each palm pad at q = 0 (``fit_hand_pads.palm_soft_tissue_mm``)."""
    pads = _pads()
    data = mujoco.MjData(model)
    mujoco.mj_forward(model, data)
    return {
        row["name"]: pads.palm_soft_tissue_mm(model, data, row["name"], row["bones"])
        for row in pads.load_table()["palm"]
        if mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_GEOM, row["name"]) >= 0
    }


def _subtree(model: mujoco.MjModel, root: str) -> set[int]:
    """Ids of a body and all its descendants."""
    top = model.body(root).id
    out = set()
    for b in range(model.nbody):
        a = b
        while a > 0 and a != top:
            a = model.body_parentid[a]
        if a == top:
            out.add(b)
    return out


def palm_geoms(model: mujoco.MjModel) -> list[int]:
    return [g for b in METACARPAL_BODIES for g in _body_geoms(model, b) if _collision(model, g)]


def fist(model_name: str = "myoarm_r") -> dict[str, Any]:
    """Active fist: FDS and FDP at full activation for FIST_SECONDS, wrist neutral, thumb locked at 0.

    Shoulder, elbow (90 deg) and forearm are held as in the McFarland scenes; MCP abduction is free.
    Collisions are those of the model's own contact pairs. Returns the fingertip-to-palm distance per
    digit (distal capsule or pad to the nearest palm geom; negative = penetration) and the deepest
    contact penetration between two hand geoms (carpus and distal) over the last 0.2 s.
    """
    vhf = _validator()
    hand = vhf.myohand()
    table = vhf.load_table()
    locks = {k: 0.0 for k in (*vhf.ARM, *vhf.WRIST, *vhf.THUMB)} | {"elbow_flexion": 90.0}
    scene = vhf.build_scene(hand, locks, table, keep_model_pairs=True)
    model = scene.model
    data = vhf.start(scene, locks)
    flexors = [n for n in (*hand.muscles["FDS"], *hand.muscles["FDP"])]
    vhf.set_activation(scene, data, {n: 1.0 for n in flexors})
    hand_bodies = _subtree(model, "lunate_r")
    steps = int(round(FIST_SECONDS / model.opt.timestep))
    deepest = 0.0
    for i in range(steps):
        mujoco.mj_step(model, data)
        if i >= steps - int(round(0.2 / model.opt.timestep)):
            for c in data.contact[: data.ncon]:
                if c.exclude == 0 and model.geom_bodyid[c.geom1] in hand_bodies and model.geom_bodyid[c.geom2] in hand_bodies:
                    deepest = min(deepest, float(c.dist - c.includemargin))  # beyond the pair's margin
    palm = palm_geoms(model)
    gaps = {}
    for digit in DIGITS:
        tips = [g for g in _body_geoms(model, DISTAL_BODIES[digit]) if _collision(model, g)]
        fromto = np.zeros(6)
        gaps[str(digit)] = 1000.0 * min(mujoco.mj_geomDistance(model, data, a, b, 0.1, fromto) for a in tips for b in palm)
    hand_pairs = sum(
        model.geom_bodyid[model.pair_geom1[i]] in hand_bodies and model.geom_bodyid[model.pair_geom2[i]] in hand_bodies
        for i in range(model.npair)
    )
    penetration = max(0.0, -1000.0 * deepest) if hand_pairs else "no hand pairs"
    return {"tip_to_palm_mm": gaps, "max_penetration_mm": penetration, "hand_pairs": int(hand_pairs)}


def pip_limits(model: mujoco.MjModel) -> list[float]:
    """Upper (flexion) limit of the PIP joints of digits 2-5 (deg)."""
    return [float(np.degrees(model.jnt_range[model.joint(f"pm{d}_flexion_r").id][1])) for d in DIGITS]


def _arms(model: mujoco.MjModel, tendon: str, posture: dict[str, float], joints: tuple[str, ...]) -> list[float]:
    """dL/dq (mm) of *tendon* about *joints* at *posture* (central differences)."""
    data = mujoco.MjData(model)

    def length(extra: dict[str, float]) -> float:
        data.qpos[:] = model.qpos0
        for joint, q in (posture | extra).items():
            data.qpos[model.joint(joint).qposadr[0]] = q
        mujoco.mj_kinematics(model, data)
        mujoco.mj_comPos(model, data)
        mujoco.mj_tendon(model, data)
        return float(data.ten_length[model.tendon(tendon).id])

    h = 1e-6
    return [(length({j: posture.get(j, 0.0) + h}) - length({j: posture.get(j, 0.0) - h})) / (2 * h) * 1e3 for j in joints]


def hypothenar(model: mujoco.MjModel) -> dict[str, Any]:
    """ADM moment arms, little-finger abduction moment and active cupping, if the model has ADM."""
    if mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_ACTUATOR, "ADM_r") < 0:
        return {}
    arms = _arms(model, "ADM_r_tendon", {}, ("mcp5_flexion_r", "mcp5_abduction_r"))
    data = mujoco.MjData(model)
    for name in ("ADM_r", "FDM_r"):
        data.act[model.actuator(name).id] = 1.0
    mujoco.mj_forward(model, data)
    moment = abs(float(data.qfrc_actuator[model.joint("mcp5_abduction_r").dofadr[0]]))
    data = mujoco.MjData(model)
    for name in ("ODM_r", "FDM_r", "ADM_r"):
        data.ctrl[model.actuator(name).id] = 1.0
    for _ in range(int(round(1.0 / model.opt.timestep))):
        mujoco.mj_step(model, data)
    cupping = [float(np.degrees(data.qpos[model.joint(f"cmc{d}_flexion_r").qposadr[0]])) for d in (4, 5)]
    return {"adm_moment_arms": [-arms[0], arms[1]], "little_abduction_moment": moment, "hypothenar_cupping": cupping}


def cmc45(model: mujoco.MjModel) -> dict[str, Any]:
    """CMC4/5 arcs, flexion limits and coupling ratio, if the model has the joints."""
    if mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, "cmc4_flexion_r") < 0:
        return {}
    ranges = [np.degrees(model.jnt_range[model.joint(f"cmc{d}_flexion_r").id]) for d in (4, 5)]
    return {
        "cmc45_arc": [float(r[1] - r[0]) for r in ranges],
        "cmc45_active_flexion": [float(r[1]) for r in ranges],
        "cmc45_coupling": float(model.eq_data[model.equality("cmc45_coupling_r").id][1]),
    }


def intrinsic_moment_arms(model: mujoco.MjModel) -> dict[str, Any]:
    """Thumb intrinsic moment arms (and FPL's and APL's) at the Smutz 1998 neutral and the first dorsal interosseous at
    MCP2 (mm)."""
    out: dict[str, Any] = {}
    names = {model.actuator(i).name for i in range(model.nu)}
    if "AdPt_r" not in names:
        return out
    neutral = {j: float(np.mean(model.joint(j).range)) for j in ("cmc_flexion_r", "cmc_abduction_r")}
    thumb = ("cmc_flexion_r", "cmc_abduction_r", "mp_flexion_r")
    force = {m: float(model.actuator_gainprm[model.actuator(f"{m}_r").id][2]) for m in ("FPBs", "FPBd", "DI1s", "DI1d")}
    out["op_moment_arms"] = _arms(model, "OP_r_tendon", neutral, thumb[:2])
    out["adpt_moment_arms"] = _arms(model, "AdPt_r_tendon", neutral, thumb)
    out["adpo_moment_arms"] = _arms(model, "AdPo_r_tendon", neutral, thumb)
    heads = {m: np.array(_arms(model, f"{m}_r_tendon", neutral, thumb)) for m in ("FPBs", "FPBd")}
    out["fpb_moment_arms"] = list(
        (force["FPBs"] * heads["FPBs"] + force["FPBd"] * heads["FPBd"]) / (force["FPBs"] + force["FPBd"])
    )
    out["apb_moment_arms"] = _arms(model, "APB_r_tendon", neutral, thumb)
    out["fpl_moment_arms"] = _arms(model, "FPL_r_tendon", neutral, thumb)
    out["apl_moment_arms"] = _arms(model, "APL_r_tendon", neutral, thumb[:2])
    di1 = []
    for joint, degs in (("mcp2_flexion_r", np.linspace(0.0, 90.0, 10)), ("mcp2_abduction_r", np.linspace(-15.0, 15.0, 7))):
        mean = {
            m: np.mean([_arms(model, f"{m}_r_tendon", {joint: float(np.radians(d))}, (joint,))[0] for d in degs])
            for m in ("DI1s", "DI1d")
        }
        di1.append(-(force["DI1s"] * mean["DI1s"] + force["DI1d"] * mean["DI1d"]) / (force["DI1s"] + force["DI1d"]))
    out["di1_moment_arms"] = di1
    data = mujoco.MjData(model)
    data.act[:] = 0.0
    for m in ("DI1s", "DI1d"):
        data.act[model.actuator(f"{m}_r").id] = 1.0
    mujoco.mj_forward(model, data)
    out["index_abduction_moment"] = float(data.qfrc_actuator[model.joint("mcp2_abduction_r").dofadr[0]])
    return out


def _held(model: mujoco.MjModel, joints: tuple[str, ...]) -> None:
    """Hold *joints* in place (heavy armature and damping), gravity off."""
    model.opt.gravity[:] = 0.0
    for name in joints:
        dof = model.joint(name).dofadr[0]
        model.dof_armature[dof] = model.dof_damping[dof] = 1e4


def extensor_mechanism(model: mujoco.MjModel) -> dict[str, Any]:
    """Index extensor-mechanism quantities: IP moment arms, ORL shares, intrinsic-plus posture, IP coupling."""
    out: dict[str, Any] = {}
    for key, tendon in (("edc_ip", "EDC2"), ("eip_ip", "EIP"), ("lumbrical_ip", "LUM1"), ("ui_ip", "PI1")):
        arms = []
        for joint, span in (("md2_flexion_r", (0.0, 60.0)), ("pm2_flexion_r", (0.0, 90.0))):
            arms.append(
                float(
                    np.mean(
                        [
                            _arms(model, f"{tendon}_r_tendon", {joint: np.radians(d)}, (joint,))[0]
                            for d in np.linspace(*span, 10)
                        ]
                    )
                )
            )
        out[f"{key}_moment_arms"] = arms
    out["orl_share"] = orl_shares(model)
    held = ("flexion_r", "deviation_r", "pro_sup_r", "elbow_flexion_r", "mcp2_abduction_r")
    m = copy.deepcopy(model)
    _held(m, held)
    data = mujoco.MjData(m)
    for joint, deg in (("mcp2_flexion_r", 90.0), ("pm2_flexion_r", 100.0), ("md2_flexion_r", 70.0)):
        data.qpos[m.joint(joint).qposadr[0]] = np.radians(deg)
    _validator().place_tendon_nodes(m, data)
    index = [n for n in ("DI1d_r", "DI1s_r", "LUM1_r", "PI1_r") if mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_ACTUATOR, n) >= 0]
    for name in index:
        data.act[m.actuator(name).id] = data.ctrl[m.actuator(name).id] = 1.0
    for _ in range(int(round(1.0 / m.opt.timestep))):
        mujoco.mj_step(m, data)
    out["intrinsic_plus"] = [
        float(np.degrees(data.qpos[m.joint(j).qposadr[0]])) for j in ("mcp2_flexion_r", "pm2_flexion_r", "md2_flexion_r")
    ]
    out["ip_coupling_slope"] = ip_coupling(model)
    return out


def orl_shares(model: mujoco.MjModel) -> list[float]:
    """Index ORL share (%) of the passive DIP moment at DIP 45 deg, PIP 0/30/60/90, MCP 0, 1.96 N on EDC2 (Ueba 2011)."""
    if mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_TENDON, "lig_ORL2_r") < 0:
        return [0.0, 0.0, 0.0, 0.0]
    data = mujoco.MjData(model)
    dof = model.joint("md2_flexion_r").dofadr[0]
    t = model.tendon("lig_ORL2_r").id
    shares = []
    for pip in (0.0, 30.0, 60.0, 90.0):
        data.qpos[:] = model.qpos0
        data.qpos[model.joint("pm2_flexion_r").qposadr[0]] = np.radians(pip)
        data.qpos[model.joint("md2_flexion_r").qposadr[0]] = np.radians(45.0)
        data.qvel[:] = data.act[:] = data.ctrl[:] = 0.0
        _validator().place_tendon_nodes(model, data)
        mujoco.mj_forward(model, data)
        jac = np.zeros((model.ntendon, model.nv))
        mujoco.mju_sparse2dense(jac, data.ten_J, model.ten_J_rownnz, model.ten_J_rowadr, model.ten_J_colind)
        stretch = max(0.0, data.ten_length[t] - model.tendon_lengthspring[t][1])
        orl = model.tendon_stiffness[t] * stretch * jac[t, dof]
        preload = 1.96 * jac[model.tendon("EDC2_r_tendon").id, dof]
        actuator = fold_node_forces(model, data, data.qfrc_actuator)  # node forces reach the joints via the ties
        total = data.qfrc_passive[dof] + actuator[dof] - preload
        shares.append(float(100.0 * orl / -total) if total < 0 else 0.0)
    return shares


def ip_coupling(model: mujoco.MjModel) -> list[float]:
    """dDIP/dPIP of the index driven by FDP2 alone (activation ramp 0-1 over 3 s), MCP held at 0, at PIP 0 / 70 / 100 deg."""
    m = copy.deepcopy(model)
    _held(m, ("flexion_r", "deviation_r", "pro_sup_r", "elbow_flexion_r", "mcp2_flexion_r", "mcp2_abduction_r"))
    data = mujoco.MjData(m)
    fdp = m.actuator("FDP2_r").id
    steps = int(round(3.0 / m.opt.timestep))
    pip, dip = [], []
    for k in range(steps):
        data.ctrl[fdp] = (k + 1) / steps
        mujoco.mj_step(m, data)
        pip.append(np.degrees(data.qpos[m.joint("pm2_flexion_r").qposadr[0]]))
        dip.append(np.degrees(data.qpos[m.joint("md2_flexion_r").qposadr[0]]))
    pip, dip = np.array(pip), np.array(dip)
    out = []
    for target in (0.0, 70.0, 100.0):
        sel = np.abs(pip - target) <= 5.0 if target > 0 else pip <= 5.0
        if pip.max() < target + 5.0 or sel.sum() < 3:  # the ramp does not carry the PIP through the window
            out.append(float("nan"))
            continue
        out.append(float(np.polyfit(pip[sel], dip[sel], 1)[0]))
    return out


# Interossei and lumbricals (S5): muscle -> digit, side of its abduction arm (+1 = ulnar) and whether its target is
# An 1983's range average (index) or An 1979's value at rest (digits 3-5).
INTEROSSEI_LUMBRICALS = {
    "PI1": (2, 1.0),
    "LUM1": (2, -1.0),
    "DI2": (3, -1.0),
    "LUM2": (3, -1.0),
    "DI3": (3, 1.0),
    "PI2": (4, -1.0),
    "LUM3": (4, -1.0),
    "DI4": (4, 1.0),
    "PI3": (5, -1.0),
    "LUM4": (5, -1.0),
}


def interossei_lumbricals(model: mujoco.MjModel) -> dict[str, Any]:
    """MCP flexion and abduction arms (mm, magnitudes in the muscle's direction) and the index intrinsic forces."""
    if mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_ACTUATOR, "LUM1_r") < 0:
        return {}
    out: dict[str, Any] = {}
    for name, (digit, side) in INTEROSSEI_LUMBRICALS.items():
        joints = (f"mcp{digit}_flexion_r", f"mcp{digit}_abduction_r")
        if digit == 2:  # averaged over the range, as An 1983
            flexion = np.mean(
                [_arms(model, f"{name}_r_tendon", {joints[0]: q}, joints[:1])[0] for q in np.radians(np.linspace(0, 90, 10))]
            )
            abduction = np.mean(
                [_arms(model, f"{name}_r_tendon", {joints[1]: q}, joints[1:])[0] for q in np.radians(np.linspace(-15, 15, 7))]
            )
        else:
            flexion, abduction = _arms(model, f"{name}_r_tendon", {}, joints)
        out[f"{name.lower()}_moment_arms"] = [float(-flexion), float(side * abduction)]
    out["index_intrinsic_forces"] = [
        float(sum(model.actuator_gainprm[model.actuator(n).id][2] for n in ("DI1d_r", "DI1s_r"))),
        float(model.actuator_gainprm[model.actuator("PI1_r").id][2]),
        float(model.actuator_gainprm[model.actuator("LUM1_r").id][2]),
    ]
    return out


def lumbrical_nodes(model: mujoco.MjModel) -> dict[str, Any]:
    """Lumbrical lengthening from the straight finger to the digit's flexion limits (mm, nodes on their ties)
    and LUM1's MCP2 flexion dL/dq at rest with the node following its FDP (mm, positive = lengthens)."""
    if mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, "node_LUM1_r") < 0:
        return {}
    validator = _validator()
    data = mujoco.MjData(model)
    validator.place_tendon_nodes(model, data)
    mujoco.mj_forward(model, data)
    straight = data.actuator_length.copy()
    excursion = []
    for n, digit in zip((1, 2, 3, 4), (2, 3, 4, 5)):
        data.qpos[:] = model.qpos0
        for joint in (f"mcp{digit}_flexion_r", f"pm{digit}_flexion_r", f"md{digit}_flexion_r"):
            data.qpos[model.joint(joint).qposadr[0]] = model.jnt_range[model.joint(joint).id][1]
        validator.place_tendon_nodes(model, data)
        mujoco.mj_forward(model, data)
        lum = model.actuator(f"LUM{n}_r").id
        excursion.append(1e3 * float(data.actuator_length[lum] - straight[lum]))
    lengths = []
    for dq in (1e-5, -1e-5):
        data.qpos[:] = model.qpos0
        data.qpos[model.joint("mcp2_flexion_r").qposadr[0]] = dq
        validator.place_tendon_nodes(model, data)
        mujoco.mj_forward(model, data)
        lengths.append(float(data.actuator_length[model.actuator("LUM1_r").id]))
    return {"lumbrical_excursion": excursion, "lum1_systemic_mcp_arm": 1e3 * (lengths[0] - lengths[1]) / 2e-5}


def extrinsic_revisions(model: mujoco.MjModel) -> dict[str, Any]:
    """S7: junctura share of the neighbour MP extension under 1.5 kg on EDC4 / EDC3 (deg, links minus no links,
    myohand_r protocol of ``generate_extrinsic_muscles.py``), FCU flexion / ulnar and ECU extension / ulnar
    moment arms at wrist neutral (mm; ECU in supination / neutral / pronation each), FDS5 force (N, % of FDS4) and the
    ECRL, ECRB and FCR extension / ulnar-deviation arms at wrist neutral (mm; wrap-side revision)."""
    if mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_TENDON, "lig_JT34_r") < 0:
        return {}
    gen = _load_script("generate_extrinsic_muscles")
    table = gen.load_table()
    k = {n: v["stiffness_N_per_m"]["value"] for n, v in table["juncturae"]["links"].items()}
    scene = gen._hand_scene()
    share = {}
    for tendon, joints in (("EDC4", ("mcp3_flexion", "mcp5_flexion")), ("EDC3", ("mcp4_flexion", "mcp5_flexion"))):
        with_links, without = gen.traction_transfer(k, tendon, scene), gen.traction_transfer(None, tendon, scene)
        share[tendon] = [with_links[j] - without[j] for j in joints]
    ecu_ext, ecu_uln = gen.ecu_rotation_arms(model, table)  # supination / neutral / pronation
    force = {n: model.actuator_gainprm[model.actuator(f"{n}_r").id][2] for n in ("FDS4", "FDS5")}
    wrist = {}  # wrap-side revision: extension (+) and ulnar-deviation (+) arms at wrist and forearm neutral
    for name in ("ECRL", "ECRB", "FCR"):
        data = mujoco.MjData(model)
        t = model.tendon(f"{name}_r_tendon").id
        wrist[f"{name.lower()}_moment_arms"] = [gen._arm(model, data, t, j, {}) for j in ("flexion_r", "deviation_r")]
    return wrist | {
        "juncturae_ring_traction": share["EDC4"],
        "juncturae_middle_traction": share["EDC3"],
        "fcu_moment_arms": list(gen.fcu_arms(model)),
        "ecu_extension_rotation": ecu_ext,
        "ecu_ulnar_rotation": ecu_uln,
        "fds5_force": [force["FDS5"], 100.0 * force["FDS5"] / force["FDS4"]],
    }


# Forearm rotators of Haugstvedt et al. 2001 (Fig. 3): model actuators and their weights (peak force).
PROSUP_MUSCLES = {"biceps": ("BIClong_r", "BICshort_r"), "supinator": ("SUP_r",), "pt": ("PT_r",), "pq": ("PQ_r",)}
PROSUP_MUSCLES |= {"ecu": ("ECU_r",), "fcu": ("FCU_r",)}


def forearm_rotation(model: mujoco.MjModel) -> dict[str, Any]:
    """Forearm rotation axis against the radial and ulnar heads (mm; ``generate_extrinsic_muscles.axis_offsets``)
    and the rotators' supination moment arms at elbow 90 deg, wrist neutral, in supination / neutral / pronation
    (mm, dL/dq of ``pro_sup_r``, + = pronation, so positive = supinator; heads weighted by peak force)."""
    if mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, "pro_sup_r") < 0:
        return {}
    gen = _load_script("generate_extrinsic_muscles")
    table = gen.load_table()
    offsets = gen.axis_offsets(model, table)
    data = mujoco.MjData(model)
    out: dict[str, Any] = {
        "forearm_axis_radial_head": offsets["radial_head_mm"],
        "forearm_axis_ulnar_head": offsets["ulnar_head_posterior_mm"],
    }
    for key, names in PROSUP_MUSCLES.items():
        acts = [model.actuator(n).id for n in names]
        weights = np.array([model.actuator_gainprm[a][2] for a in acts])
        values = []
        for deg in table["ecu"]["rotations_deg"]:
            arms = []
            for a in acts:
                lengths = []
                for h in (1e-5, -1e-5):
                    data.qpos[:] = model.qpos0
                    data.qpos[model.joint("elbow_flexion_r").qposadr[0]] = np.pi / 2
                    data.qpos[model.joint("pro_sup_r").qposadr[0]] = np.radians(deg) + h
                    mujoco.mj_fwdPosition(model, data)
                    lengths.append(data.actuator_length[a])
                arms.append((lengths[0] - lengths[1]) / 2e-5 * 1e3)
            values.append(float(np.dot(weights, arms) / weights.sum()))
        out[f"prosup_moment_arms_{key}"] = values
    return out


def measure(model_name: str = "myoarm_r") -> dict[str, Any]:
    import myo_sim

    model = myo_sim.load_model(model_name)
    out: dict[str, Any] = (
        {"pip_flexion_limit": pip_limits(model)} | cmc45(model) | intrinsic_moment_arms(model) | hypothenar(model)
    )
    out |= interossei_lumbricals(model)
    out |= extensor_mechanism(model)
    out |= lumbrical_nodes(model)
    out |= extrinsic_revisions(model)
    out |= forearm_rotation(model)
    out["fingertip_pad_thickness"] = fingertip_pads(model)
    pads = palm_pads(model)
    out["palm_pad_thickness"] = pads or "no palm pads"
    f = fist(model_name)
    out["fist_tip_to_palm"] = f["tip_to_palm_mm"]
    out["fist_max_penetration"] = f["max_penetration_mm"]
    return out


# --- hand-function results (scripts/validate_hand_function.py) ------------------------------------------


def from_hand_function(results: dict[str, Any]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    if "tenodesis" in results:
        a, b = results["tenodesis"]["A"], results["tenodesis"]["B"]
        out["tenodesis_mcp_rom"] = [a["rom_deg"][f"mcp_flexion{d}"] for d in DIGITS]
        out["tenodesis_pip_rom"] = a["mean_rom_pip_flexion"]
        out["tenodesis_index_gap"] = [a["index_gap_mcp_flexion"], a["index_gap_pip_flexion"]]
        out["tenodesis_release"] = [b["net_deg"][f"mcp_flexion{d}"] for d in DIGITS]
    if "grip" in results:
        g = results["grip"]
        base = g["self_selected"]["balanced"]
        out["grip_self_selected"] = base["grip"]
        out["grip_settled"] = base.get("settled", {}).get("grip")
        out["grip_shares"] = [100.0 * base["share"][str(d)] for d in DIGITS]
        out["grip_posture_change"] = [100.0 * (g[k]["balanced"]["grip"] / base["grip"] - 1.0) for k in ("neutral", "flexed")]
    if "pinch" in results:
        p = results["pinch"]
        out["lateral_pinch"] = p["force_N"] if p.get("feasible") else "none"
    return out


# --- rendering --------------------------------------------------------------------------------------------


def _fmt(value: Any, unit: str = "") -> str:
    if value is None:
        return "–"
    if isinstance(value, str):
        return value
    if isinstance(value, dict):
        return " / ".join(_fmt(v) for v in value.values())
    if isinstance(value, list | tuple):
        return " / ".join(_fmt(v) for v in value)
    if isinstance(value, float) and np.isnan(value):
        return "–"
    return f"{value:.1f}" if abs(value) < 1000 else f"{value:.0f}"


def _literature(entry: dict[str, Any]) -> str:
    value = _fmt(entry["value"])
    if entry.get("spread") is not None:
        value += f" ± {_fmt(entry['spread'])}" + (f" ({entry['spread_kind']})" if entry.get("spread_kind") else "")
    return f"{value}; {entry['kind']}"


def _reference(data: dict[str, Any], key: str | None) -> str:
    return data["sources"][key]["short"] if key else "–"


def render_step(data: dict[str, Any], step: dict[str, Any]) -> str:
    lines = [f"### {step['title']}", "", step["summary"], ""]
    before = step.get("before")
    header = (
        "| Quantity | Model" + (f" ({before['label']})" if before else "") + " | " + ("Model (before) | " if before else "")
    )
    header += "Literature (± spread) | Reference | Protocol / posture |"
    lines += [header, "| " + " | ".join(["---"] * (header.count("|") - 1)) + " |"]
    for key, value in step["values"].items():
        q = data["quantities"][key]
        for i, entry in enumerate(q["literature"]):
            label = f"{q['label']} ({q['unit']})" if i == 0 else "″"
            model = _fmt(value) if i == 0 else ""
            row = [label, model]
            if before:
                row.append(_fmt(before["values"].get(key)) if i == 0 else "")
            row += [_literature(entry), _reference(data, entry.get("source")), entry["protocol"]]
            lines.append("| " + " | ".join(row) + " |")
    if step.get("notes"):
        lines += [""] + [f"- {note}" for note in step["notes"]]
    return "\n".join(lines)


def render(data: dict[str, Any]) -> str:
    parts = [BEGIN, ""]
    for step in data["steps"]:
        parts += [render_step(data, step), ""]
    parts += ["### References", ""]
    for key, source in data["sources"].items():
        doi = f" doi:{source['doi']}" if source.get("doi") else ""
        parts.append(f"- **{source['short']}**: {source['citation']}{doi} {source.get('note', '')}".rstrip())
    parts += ["", END]
    return "\n".join(parts)


def write_wiki(data: dict[str, Any], path: Path = WIKI_PATH) -> None:
    text = path.read_text()
    start, end = text.index(BEGIN), text.index(END) + len(END)
    path.write_text(text[:start] + render(data) + text[end:])


def wiki_block(path: Path = WIKI_PATH) -> str:
    text = path.read_text()
    return text[text.index(BEGIN) : text.index(END) + len(END)]


def _jsonable(x: Any) -> Any:
    if isinstance(x, dict):
        return {k: _jsonable(v) for k, v in x.items()}
    if isinstance(x, list | tuple):
        return [_jsonable(v) for v in x]
    if isinstance(x, float | np.floating):
        return None if np.isnan(x) else round(float(x), 2)
    return x


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--measure", action="store_true", help="print the geometric quantities of the current model")
    parser.add_argument("--record", metavar="ID", help="record the current model values as step ID")
    parser.add_argument("--title")
    parser.add_argument("--summary", default="")
    parser.add_argument("--hand-function", type=Path, help="results JSON of scripts/validate_hand_function.py")
    parser.add_argument("--before", metavar="ID", help="show the values of step ID next to the new ones")
    parser.add_argument("--note", action="append", default=[])
    args = parser.parse_args()
    data = load_data()
    if args.measure or args.record:
        values = measure()
        if args.hand_function:
            values = from_hand_function(json.loads(args.hand_function.read_text())) | values
        print(json.dumps(_jsonable(values), indent=1))
    if args.record:
        step = {"id": args.record, "title": args.title or args.record, "summary": args.summary, "values": _jsonable(values)}
        if args.before:
            previous = next(s for s in data["steps"] if s["id"] == args.before)
            step["before"] = {"label": args.record, "id": args.before, "values": previous["values"]}
        if args.note:
            step["notes"] = args.note
        data["steps"] = [s for s in data["steps"] if s["id"] != args.record] + [step]
        DATA_PATH.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    write_wiki(data)


if __name__ == "__main__":
    main()
