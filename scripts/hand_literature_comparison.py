"""Compare the hand model with published data, step by step, and write the wiki tables.

The literature values, their sources and protocols are in ``build/data/hand_literature.json``
(``quantities``); the model values recorded after each change of the hand are in its ``steps``. The
wiki page ``docs/wiki/hand-literature-comparison.md`` is generated from that file::

    python scripts/hand_literature_comparison.py                       # rewrite the wiki tables only
    python scripts/hand_literature_comparison.py --measure             # print the current model values
    python scripts/hand_literature_comparison.py --record s1 --title "..." --summary "..." \\
        --hand-function results.json                                   # record a step

``--hand-function`` reads the JSON written by ``scripts/validate_hand_function.py --out`` (tenodesis,
grip, pinch); the geometric quantities (pads, fist) are measured here on ``myoarm_r``. The script uses
whichever ``myo_sim`` is importable.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path
from typing import Any

import mujoco
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = ROOT / "myo_sim" / "build" / "data" / "hand_literature.json"
WIKI_PATH = ROOT / "docs" / "wiki" / "hand-literature-comparison.md"
BEGIN = "<!-- BEGIN generated by scripts/hand_literature_comparison.py; do not edit by hand -->"
END = "<!-- END generated -->"
DIGITS = (2, 3, 4, 5)
# Distal-phalanx body of each digit (the thumb last).
DISTAL_BODIES = {**{d: f"distph{d}_r" for d in DIGITS}, "thumb": "distal_thumb_r"}
PALM_PADS = ("palm_pad_r", "thenar_pad_r", "hypothenar_pad_r")
METACARPAL_BODIES = ("firstmc_r", "secondmc_r", "thirdmc_r", "fourthmc_r", "fifthmc_r")
FIST_SECONDS = 1.0


def load_data(path: Path = DATA_PATH) -> dict[str, Any]:
    return json.loads(path.read_text())


def _validator() -> Any:
    if "validate_hand_function" in sys.modules:
        return sys.modules["validate_hand_function"]
    spec = importlib.util.spec_from_file_location(
        "validate_hand_function", Path(__file__).with_name("validate_hand_function.py")
    )
    module = importlib.util.module_from_spec(spec)
    sys.modules["validate_hand_function"] = module
    spec.loader.exec_module(module)
    return module


# --- geometry ---------------------------------------------------------------------------------------------


def _body_geoms(model: mujoco.MjModel, body: str) -> list[int]:
    b = model.body(body).id
    return [g for g in range(model.ngeom) if model.geom_bodyid[g] == b]


def _collision(model: mujoco.MjModel, g: int) -> bool:
    return model.geom_group[g] == 4 and model.geom_type[g] != mujoco.mjtGeom.mjGEOM_MESH


def _ray_geom(model: mujoco.MjModel, data: mujoco.MjData, g: int, pnt: np.ndarray, vec: np.ndarray) -> float:
    if model.geom_type[g] == mujoco.mjtGeom.mjGEOM_MESH:
        return mujoco.mj_rayMesh(model, data, g, pnt, vec)
    return mujoco.mju_rayGeom(data.geom_xpos[g], data.geom_xmat[g], model.geom_size[g], pnt, vec, model.geom_type[g])


def _pad_axis(model: mujoco.MjModel, data: mujoco.MjData, pad: int, bone: int) -> np.ndarray:
    """Unit outward normal of a pad: its shortest semi-axis, pointing away from the bone."""
    axis = data.geom_xmat[pad].reshape(3, 3)[:, int(np.argmin(model.geom_size[pad]))]
    return axis if np.dot(data.geom_xpos[pad] - data.geom_xpos[bone], axis) > 0 else -axis


def soft_tissue_mm(model: mujoco.MjModel, data: mujoco.MjData, pad: int, bones: list[int], skin: list[int]) -> float:
    """Largest soft-tissue thickness normal to a pad (mm), as Dallard 2018 measure it.

    Rays parallel to the pad normal are cast towards the bone over a grid covering the pad; on each ray
    the thickness is the distance from the outermost skin geom to the bone. The largest value is returned.
    """
    normal = _pad_axis(model, data, pad, bones[0])
    axes = data.geom_xmat[pad].reshape(3, 3)
    order = np.argsort(model.geom_size[pad])
    best = float("nan")
    for u in np.linspace(-1.0, 1.0, 11):
        for v in np.linspace(-1.0, 1.0, 11):
            offset = (
                u * model.geom_size[pad][order[2]] * axes[:, order[2]] + v * model.geom_size[pad][order[1]] * axes[:, order[1]]
            )
            start = data.geom_xpos[pad] + offset + 0.05 * normal
            hits_skin = [x for x in (_ray_geom(model, data, g, start, -normal) for g in skin) if x >= 0]
            hits_bone = [x for x in (_ray_geom(model, data, g, start, -normal) for g in bones) if x >= 0]
            if hits_skin and hits_bone:
                thickness = 1000.0 * (min(hits_bone) - min(hits_skin))
                best = thickness if np.isnan(best) else max(best, thickness)
    return best


def _mesh_vertices(model: mujoco.MjModel, data: mujoco.MjData, g: int) -> np.ndarray:
    mesh = model.geom_dataid[g]
    local = model.mesh_vert[model.mesh_vertadr[mesh] : model.mesh_vertadr[mesh] + model.mesh_vertnum[mesh]]
    return local @ data.geom_xmat[g].reshape(3, 3).T + data.geom_xpos[g]


def fingertip_soft_tissue_mm(model: mujoco.MjModel, data: mujoco.MjData, body: str) -> float:
    """Palmar soft tissue of a fingertip at q = 0 (mm), measured like Dallard 2018's D_N0.

    D_N0 runs from the distal palmar corner of the phalanx perpendicular to its long axis to the skin
    (Dallard Fig. 2); its mean is their "maximal thickness". Here: the long axis runs from the joint centre
    to the farthest bone vertex, the palmar direction is the pad normal made perpendicular to it, and
    palmar rays through the bone's mid-line over its last 6 mm give the skin (outermost collision geom)
    to bone distance; the largest is returned.
    """
    geoms = _body_geoms(model, body)
    bone = next(g for g in geoms if model.geom_type[g] == mujoco.mjtGeom.mjGEOM_MESH)
    skin = [g for g in geoms if _collision(model, g)]
    pad = next(g for g in skin if model.geom_type[g] == mujoco.mjtGeom.mjGEOM_ELLIPSOID)
    origin = data.xpos[model.body(body).id]
    verts = _mesh_vertices(model, data, bone)
    tip = verts[np.argmax(np.linalg.norm(verts - origin, axis=1))]
    axis = (tip - origin) / np.linalg.norm(tip - origin)
    palmar = _pad_axis(model, data, pad, bone)
    palmar = palmar - np.dot(palmar, axis) * axis
    palmar /= np.linalg.norm(palmar)
    lateral = np.cross(axis, palmar)
    centre = np.mean(verts @ lateral) * lateral
    length = np.dot(tip - origin, axis)
    best = float("nan")
    for station in np.arange(length - 0.006, length, 0.0002):
        start = origin + station * axis - np.dot(origin, lateral) * lateral + centre + 0.05 * palmar
        bone_hit = _ray_geom(model, data, bone, start, -palmar)
        skin_hits = [x for x in (_ray_geom(model, data, g, start, -palmar) for g in skin) if x >= 0]
        if bone_hit >= 0 and skin_hits:
            thickness = 1000.0 * (bone_hit - min(skin_hits))
            best = thickness if np.isnan(best) else max(best, thickness)
    return best


def fingertip_pads(model: mujoco.MjModel) -> dict[str, float]:
    """Fingertip soft tissue (Dallard 2018's D_N0) of digits 2-5 and the thumb at q = 0."""
    data = mujoco.MjData(model)
    mujoco.mj_forward(model, data)
    return {str(digit): fingertip_soft_tissue_mm(model, data, body) for digit, body in DISTAL_BODIES.items()}


def palm_pads(model: mujoco.MjModel) -> dict[str, float]:
    """Soft tissue under each palm pad (pad surface to the nearest metacarpal bone along the pad normal)."""
    data = mujoco.MjData(model)
    mujoco.mj_forward(model, data)
    bones = [g for b in METACARPAL_BODIES for g in _body_geoms(model, b) if model.geom_type[g] == mujoco.mjtGeom.mjGEOM_MESH]
    out = {}
    for name in PALM_PADS:
        g = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_GEOM, name)
        if g < 0:
            continue
        own = [b for b in bones if model.geom_bodyid[b] == model.geom_bodyid[g]] or bones
        out[name] = soft_tissue_mm(model, data, g, own + [b for b in bones if b not in own], [g])
    return out


def _subtree(model: mujoco.MjModel, root: str) -> set[int]:
    """Ids of a body and all its descendants."""
    top = model.body(root).id
    out = set()
    for b in range(model.nbody):
        a = b
        while a > 0 and a != top:
            a = model.body_parentid[a]
        if a == top:
            out.add(b)
    return out


def palm_geoms(model: mujoco.MjModel) -> list[int]:
    return [g for b in METACARPAL_BODIES for g in _body_geoms(model, b) if _collision(model, g)]


def fist(model_name: str = "myoarm_r") -> dict[str, Any]:
    """Active fist: FDS and FDP at full activation for FIST_SECONDS, wrist neutral, thumb locked at 0.

    Shoulder, elbow (90 deg) and forearm are held as in the McFarland scenes; MCP abduction is free.
    Collisions are those of the model's own contact pairs. Returns the fingertip-to-palm distance per
    digit (distal capsule or pad to the nearest palm geom; negative = penetration) and the deepest
    contact penetration between two hand geoms (carpus and distal) over the last 0.2 s.
    """
    vhf = _validator()
    hand = vhf.myohand()
    table = vhf.load_table()
    locks = {k: 0.0 for k in (*vhf.ARM, *vhf.WRIST, *vhf.THUMB)} | {"elbow_flexion": 90.0}
    scene = vhf.build_scene(hand, locks, table)
    model = scene.model
    data = vhf.start(scene, locks)
    flexors = [n for n in (*hand.muscles["FDS"], *hand.muscles["FDP"])]
    vhf.set_activation(scene, data, {n: 1.0 for n in flexors})
    hand_bodies = _subtree(model, "lunate_r")
    steps = int(round(FIST_SECONDS / model.opt.timestep))
    deepest = 0.0
    for i in range(steps):
        mujoco.mj_step(model, data)
        if i >= steps - int(round(0.2 / model.opt.timestep)):
            for c in data.contact[: data.ncon]:
                if model.geom_bodyid[c.geom1] in hand_bodies and model.geom_bodyid[c.geom2] in hand_bodies:
                    deepest = min(deepest, float(c.dist))
    palm = palm_geoms(model)
    gaps = {}
    for digit in DIGITS:
        tips = [g for g in _body_geoms(model, DISTAL_BODIES[digit]) if _collision(model, g)]
        fromto = np.zeros(6)
        gaps[str(digit)] = 1000.0 * min(mujoco.mj_geomDistance(model, data, a, b, 0.1, fromto) for a in tips for b in palm)
    hand_pairs = sum(
        model.geom_bodyid[model.pair_geom1[i]] in hand_bodies and model.geom_bodyid[model.pair_geom2[i]] in hand_bodies
        for i in range(model.npair)
    )
    penetration = max(0.0, -1000.0 * deepest) if hand_pairs else "no hand pairs"
    return {"tip_to_palm_mm": gaps, "max_penetration_mm": penetration, "hand_pairs": int(hand_pairs)}


def measure(model_name: str = "myoarm_r") -> dict[str, Any]:
    import myo_sim

    model = myo_sim.load_model(model_name)
    out: dict[str, Any] = {"fingertip_pad_thickness": fingertip_pads(model)}
    pads = palm_pads(model)
    out["palm_pad_thickness"] = pads or "no palm pads"
    f = fist(model_name)
    out["fist_tip_to_palm"] = f["tip_to_palm_mm"]
    out["fist_max_penetration"] = f["max_penetration_mm"]
    return out


# --- hand-function results (scripts/validate_hand_function.py) ------------------------------------------


def from_hand_function(results: dict[str, Any]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    if "tenodesis" in results:
        a, b = results["tenodesis"]["A"], results["tenodesis"]["B"]
        out["tenodesis_mcp_rom"] = [a["rom_deg"][f"mcp_flexion{d}"] for d in DIGITS]
        out["tenodesis_pip_rom"] = a["mean_rom_pip_flexion"]
        out["tenodesis_index_gap"] = [a["index_gap_mcp_flexion"], a["index_gap_pip_flexion"]]
        out["tenodesis_release"] = [b["net_deg"][f"mcp_flexion{d}"] for d in DIGITS]
    if "grip" in results:
        g = results["grip"]
        base = g["self_selected"]["balanced"]
        out["grip_self_selected"] = base["grip"]
        out["grip_settled"] = base.get("settled", {}).get("grip")
        out["grip_shares"] = [100.0 * base["share"][str(d)] for d in DIGITS]
        out["grip_posture_change"] = [100.0 * (g[k]["balanced"]["grip"] / base["grip"] - 1.0) for k in ("neutral", "flexed")]
    if "pinch" in results:
        p = results["pinch"]
        out["lateral_pinch"] = p["force_N"] if p.get("feasible") else "none"
    return out


# --- rendering --------------------------------------------------------------------------------------------


def _fmt(value: Any, unit: str = "") -> str:
    if value is None:
        return "–"
    if isinstance(value, str):
        return value
    if isinstance(value, dict):
        return " / ".join(_fmt(v) for v in value.values())
    if isinstance(value, list | tuple):
        return " / ".join(_fmt(v) for v in value)
    if isinstance(value, float) and np.isnan(value):
        return "–"
    return f"{value:.1f}" if abs(value) < 1000 else f"{value:.0f}"


def _literature(entry: dict[str, Any]) -> str:
    value = _fmt(entry["value"])
    if entry.get("spread") is not None:
        value += f" ± {_fmt(entry['spread'])}" + (f" ({entry['spread_kind']})" if entry.get("spread_kind") else "")
    return f"{value}; {entry['kind']}"


def _reference(data: dict[str, Any], key: str | None) -> str:
    return data["sources"][key]["short"] if key else "–"


def render_step(data: dict[str, Any], step: dict[str, Any]) -> str:
    lines = [f"### {step['title']}", "", step["summary"], ""]
    before = step.get("before")
    header = (
        "| Quantity | Model" + (f" ({before['label']})" if before else "") + " | " + ("Model (before) | " if before else "")
    )
    header += "Literature (± spread) | Reference | Protocol / posture |"
    lines += [header, "| " + " | ".join(["---"] * (header.count("|") - 1)) + " |"]
    for key, value in step["values"].items():
        q = data["quantities"][key]
        for i, entry in enumerate(q["literature"]):
            label = f"{q['label']} ({q['unit']})" if i == 0 else "″"
            model = _fmt(value) if i == 0 else ""
            row = [label, model]
            if before:
                row.append(_fmt(before["values"].get(key)) if i == 0 else "")
            row += [_literature(entry), _reference(data, entry.get("source")), entry["protocol"]]
            lines.append("| " + " | ".join(row) + " |")
    if step.get("notes"):
        lines += [""] + [f"- {note}" for note in step["notes"]]
    return "\n".join(lines)


def render(data: dict[str, Any]) -> str:
    parts = [BEGIN, ""]
    for step in data["steps"]:
        parts += [render_step(data, step), ""]
    parts += ["### References", ""]
    for key, source in data["sources"].items():
        doi = f" doi:{source['doi']}" if source.get("doi") else ""
        parts.append(f"- **{source['short']}**: {source['citation']}{doi} {source.get('note', '')}".rstrip())
    parts += ["", END]
    return "\n".join(parts)


def write_wiki(data: dict[str, Any], path: Path = WIKI_PATH) -> None:
    text = path.read_text()
    start, end = text.index(BEGIN), text.index(END) + len(END)
    path.write_text(text[:start] + render(data) + text[end:])


def wiki_block(path: Path = WIKI_PATH) -> str:
    text = path.read_text()
    return text[text.index(BEGIN) : text.index(END) + len(END)]


def _jsonable(x: Any) -> Any:
    if isinstance(x, dict):
        return {k: _jsonable(v) for k, v in x.items()}
    if isinstance(x, list | tuple):
        return [_jsonable(v) for v in x]
    if isinstance(x, float | np.floating):
        return None if np.isnan(x) else round(float(x), 2)
    return x


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--measure", action="store_true", help="print the geometric quantities of the current model")
    parser.add_argument("--record", metavar="ID", help="record the current model values as step ID")
    parser.add_argument("--title")
    parser.add_argument("--summary", default="")
    parser.add_argument("--hand-function", type=Path, help="results JSON of scripts/validate_hand_function.py")
    parser.add_argument("--before", metavar="ID", help="show the values of step ID next to the new ones")
    parser.add_argument("--note", action="append", default=[])
    args = parser.parse_args()
    data = load_data()
    if args.measure or args.record:
        values = measure()
        if args.hand_function:
            values = from_hand_function(json.loads(args.hand_function.read_text())) | values
        print(json.dumps(_jsonable(values), indent=1))
    if args.record:
        step = {"id": args.record, "title": args.title or args.record, "summary": args.summary, "values": _jsonable(values)}
        if args.before:
            previous = next(s for s in data["steps"] if s["id"] == args.before)
            step["before"] = {"label": args.record, "id": args.before, "values": previous["values"]}
        if args.note:
            step["notes"] = args.note
        data["steps"] = [s for s in data["steps"] if s["id"] != args.record] + [step]
        DATA_PATH.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    write_wiki(data)


if __name__ == "__main__":
    main()
