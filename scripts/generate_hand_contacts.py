"""Select the hand self-contact pairs from a posture scan and write the shared contacts file.

The pair table is ``build/data/hand_contact_pairs.json``; the generated block in
``myo_sim/models/contacts/myohand_self_contacts.xml`` holds both hands (left names mirrored from the right
with ``MirrorRules``). Every model with a hand adds the file to its arm (``compose.py``)::

    python scripts/generate_hand_contacts.py --scan   # rescan, reselect the pairs, update table and XML
    python scripts/generate_hand_contacts.py          # write the XML from the table

**Scan.** ``myohand_r`` with wrist and forearm at 0: uniform random postures over the 20 thumb and finger
joint ranges plus the full fist (MCP, PIP, DIP at their flexion limits). For every pair of hand collision
geoms on bodies that are not the same or parent and child, the signed distance (``mj_geomDistance``):
``pen_frac`` is the share of postures with more than 2 mm penetration, ``min_mm`` the deepest, ``rest_mm``
and ``fist_mm`` the distance at q = 0 and in the fist.

**Selection.** Pairs that overlap at rest are not paired (a pair active at rest pushes the digits apart),
except the existing pairs, which get a negative ``margin``: their contact starts only beyond that
penetration (MuJoCo clamps ``margin - gap`` at zero, so a ``gap`` cannot do this). Otherwise a pair is kept when ``pen_frac`` reaches
``min_pen_frac``, or when it is functional: thumb pulp against a fingertip pad (pinch), and any finger or
thumb geom against a palm geom that it penetrates somewhere in the scan or comes within
``fist_reach_mm`` of in the fist, and always the pairs listed under ``selection.always`` (the
fingertips and the thumb against the palm and hypothenar pads).
"""

from __future__ import annotations

import argparse
import itertools
import json
from pathlib import Path
from typing import Any

import mujoco
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = ROOT / "myo_sim" / "build" / "data" / "hand_contact_pairs.json"
CONTACTS_XML = ROOT / "myo_sim" / "models" / "contacts" / "myohand_self_contacts.xml"
SCRIPT = Path(__file__).name
BEGIN = f"<!-- BEGIN generated by scripts/{SCRIPT}; do not edit by hand -->"
END = "<!-- END generated -->"
FINGER_JOINTS = tuple(f"{j}{d}_flexion_r" for d in (2, 3, 4, 5) for j in ("mcp", "pm", "md")) + tuple(
    f"mcp{d}_abduction_r" for d in (2, 3, 4, 5)
)
THUMB_JOINTS = ("cmc_flexion_r", "cmc_abduction_r", "mp_flexion_r", "ip_flexion_r")
HAND_ROOT = "lunate_r"


def load_table(path: Path = DATA_PATH) -> dict[str, Any]:
    return json.loads(path.read_text())


def _subtree(model: mujoco.MjModel, root: str) -> set[int]:
    top = model.body(root).id
    out = set()
    for b in range(model.nbody):
        a = b
        while a > 0 and a != top:
            a = model.body_parentid[a]
        if a == top:
            out.add(b)
    return out


def hand_collision_geoms(model: mujoco.MjModel) -> list[int]:
    bodies = _subtree(model, HAND_ROOT)
    return [
        g
        for g in range(model.ngeom)
        if model.geom_bodyid[g] in bodies and model.geom_group[g] == 4 and model.geom_type[g] != mujoco.mjtGeom.mjGEOM_MESH
    ]


def role(name: str, roles: dict[str, list[str]]) -> str:
    return next(r for r, names in roles.items() if name in names)


def scan(table: dict[str, Any]) -> dict[str, dict[str, float]]:
    import myo_sim

    spec = table["scan"]
    model = myo_sim.load_model("myohand_r")
    data = mujoco.MjData(model)
    geoms = hand_collision_geoms(model)
    pairs = [
        (a, b)
        for a, b in itertools.combinations(geoms, 2)
        if model.geom_bodyid[a] != model.geom_bodyid[b]
        and model.body_parentid[model.geom_bodyid[a]] != model.geom_bodyid[b]
        and model.body_parentid[model.geom_bodyid[b]] != model.geom_bodyid[a]
    ]
    joints = [model.joint(n).id for n in FINGER_JOINTS + THUMB_JOINTS]
    rng = np.random.default_rng(spec["seed"])
    fromto = np.zeros(6)

    def distances() -> np.ndarray:
        return np.array([mujoco.mj_geomDistance(model, data, a, b, 0.05, fromto) for a, b in pairs])

    def pose(values: dict[int, float]) -> None:
        data.qpos[:] = model.qpos0
        for j, v in values.items():
            data.qpos[model.jnt_qposadr[j]] = v
        mujoco.mj_forward(model, data)

    pose({})
    rest = distances()
    pose({model.joint(n).id: model.jnt_range[model.joint(n).id][1] for n in FINGER_JOINTS if "_flexion" in n})
    fist = distances()
    depth = spec["penetration_m"]
    count = np.zeros(len(pairs))
    deepest = np.full(len(pairs), np.inf)
    for _ in range(spec["postures"]):
        pose({j: rng.uniform(*model.jnt_range[j]) for j in joints})
        dist = distances()
        count += dist < -depth
        deepest = np.minimum(deepest, dist)
    out = {}
    reach = table["selection"]["fist_reach_mm"] / 1000.0
    for k, (a, b) in enumerate(pairs):
        if deepest[k] < 0 or fist[k] < reach:
            names = sorted((model.geom(a).name, model.geom(b).name))
            out[f"{names[0]} {names[1]}"] = {
                "pen_frac": round(float(count[k] / spec["postures"]), 4),
                "min_mm": round(1000 * float(min(deepest[k], fist[k])), 2),
                "rest_mm": round(1000 * float(rest[k]), 2),
                "fist_mm": round(1000 * float(fist[k]), 2),
            }
    return out


def select(table: dict[str, Any], stats: dict[str, dict[str, float]]) -> list[dict[str, Any]]:
    rules, roles = table["selection"], table["roles"]
    existing = {" ".join(sorted(p)) for p in table["existing_pairs"]}
    functional = {" ".join(sorted((a, b))) for group in rules["always"] for a in group["geoms"] for b in group["against"]}
    pairs = []
    for key in functional - set(stats):  # pairs the scan never brought close: keep them all the same
        stats[key] = {"pen_frac": 0.0, "min_mm": None, "rest_mm": None, "fist_mm": None}
    for key, s in sorted(stats.items(), key=lambda kv: (-kv[1]["pen_frac"], kv[0])):
        a, b = key.split()
        ra, rb = role(a, roles), role(b, roles)
        kinds = {ra, rb}
        at_rest = s["rest_mm"] is not None and s["rest_mm"] < rules["rest_clearance_mm"]
        if key in existing:
            group = "existing"
        elif at_rest:
            continue
        elif kinds == {"thumb_pad", "finger_pad"}:
            group = "thumb_pad_vs_finger_pads"
        elif key in functional:
            group = "fingers_and_thumb_vs_palm"
        elif (
            "palm" in kinds
            and kinds & {"finger", "finger_pad", "thumb", "thumb_pad"}
            and (s["min_mm"] < 0 or s["fist_mm"] < rules["fist_reach_mm"])
        ):
            group = "fingers_and_thumb_vs_palm"
        elif kinds & {"thumb", "thumb_pad"} and kinds & {"finger", "finger_pad"} and s["pen_frac"] >= rules["min_pen_frac"]:
            group = "thumb_vs_fingers"
        elif kinds <= {"finger", "finger_pad"} and s["pen_frac"] >= rules["min_pen_frac"]:
            group = "finger_vs_finger"
        else:
            continue
        pair = {"geom1": a, "geom2": b, "group": group, **s}
        pair["condim"] = rules["condim_pulp"] if group == "thumb_pad_vs_finger_pads" else rules["condim"]
        if key in existing and at_rest:
            pair["margin_m"] = rules["rest_margin_m"]
        pairs.append(pair)
    return pairs


def mirror(name: str) -> str:
    from myo_sim.build.utils import MirrorRules, mirror_name

    return mirror_name(name, MirrorRules())


def block(table: dict[str, Any]) -> str:
    lines = []
    for side in ("r", "l"):
        lines.append(f"        <!-- {'right' if side == 'r' else 'left'} hand -->")
        for p in table["pairs"]:
            g1, g2 = (p["geom1"], p["geom2"]) if side == "r" else (mirror(p["geom1"]), mirror(p["geom2"]))
            extra = f' margin="{p["margin_m"]:g}"' if "margin_m" in p else ""
            params = " ".join(
                f'{k}="{" ".join(f"{v:g}" for v in table["selection"][k])}"' for k in ("friction", "solref", "solimp")
            )
            lines.append(f'        <pair name="{g1}__{g2}" geom1="{g1}" geom2="{g2}" condim="{p["condim"]}" {params}{extra}/>')
    return "".join(f"{line}\n" for line in lines)


def write_xml(table: dict[str, Any], path: Path = CONTACTS_XML) -> None:
    head = (
        '<?xml version="1.0" ?>\n<mujocoinclude>\n    <!-- Self-contacts of each hand (finger, thumb and palm pads), added to every model\n'
        "         with a hand by compose.py. Pairs and parameters: build/data/hand_contact_pairs.json. -->\n    <contact>\n"
    )
    path.write_text(f"{head}        {BEGIN}\n{block(table)}        {END}\n    </contact>\n</mujocoinclude>\n")


def read_block(path: Path = CONTACTS_XML) -> str:
    text = path.read_text()
    return text[text.index(BEGIN) + len(BEGIN) + 1 : text.index(END)].rstrip(" ")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--scan", action="store_true", help="rescan the postures and reselect the pairs")
    args = parser.parse_args()
    table = load_table()
    if args.scan:
        stats = scan(table)
        table["pairs"] = select(table, stats)
        table["scan"]["penetrating_pairs"] = len(stats)
        DATA_PATH.write_text(json.dumps(table, indent=2, ensure_ascii=False) + "\n")
    write_xml(table)
    groups: dict[str, int] = {}
    for p in table["pairs"]:
        groups[p["group"]] = groups.get(p["group"], 0) + 1
    print(f"{len(table['pairs'])} pairs per hand: {groups}")


if __name__ == "__main__":
    main()
