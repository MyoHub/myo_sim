"""Fit the marker positions of the Bath running marker set to the dataset's published static trials.

Source: Carter J, Chen X, Cazzola D, Trewartha G, Preatoni E (2024). Full Body Kinematics and Ground Reaction Forces of
Fifty Heterogeneous Runners Completing Treadmill Running at Various Speeds and Gradients. University of Bath Research
Data Archive. https://doi.org/10.15125/BATH-01341 (CC BY 4.0).

Download the per-participant archives (P002.zip ... P052.zip) from https://researchdata.bath.ac.uk/1341/ into one
directory; extracted folders (P002/P002_Static_1.c3d, ...) work as well. The script reads each participant's static
standing trial, averages the first frames, and maps every recorded marker into myofullbody (default pose) by a
per-segment similarity transform fitted on the anatomical markers that sit on model landmark sites. Left-side
markers are mirrored onto the right, the median over participants and sides gives the position, and the result is
mirrored back for the left side. The positions are written into the generated blocks of
myo_sim/models/markersets/bath_running.xml, and the provenance (citation, per-marker values, fit residuals) into
myo_sim/build/data/markersets_bath.json. The raw data is only read, never copied.

Usage:
    python scripts/fit_markersets_bath.py DOWNLOAD_DIR            # fit and write XML and JSON
    python scripts/fit_markersets_bath.py DOWNLOAD_DIR --check    # fit and compare with the committed values

Requires ezc3d (pip install ezc3d) to read the C3D files; checking the XML against the JSON (the test) does not.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tempfile
import warnings
import zipfile
from collections.abc import Iterator
from pathlib import Path

import mujoco
import numpy as np

import myo_sim
from myo_sim.markersets import add_markerset, markerset_path

ROOT = Path(myo_sim.__file__).resolve().parent
XML_PATH = markerset_path("bath_running")
JSON_PATH = ROOT / "build" / "data" / "markersets_bath.json"
GENERATOR = "scripts/fit_markersets_bath.py"
BEGIN = f"<!-- BEGIN generated by {GENERATOR}; do not edit by hand -->"
END = "<!-- END generated -->"
MODEL = "myofullbody"
N_FRAMES = 200  # first 0.8 s at 250 Hz: quiet standing on both belts
DECIMALS = 4

SOURCE = {
    "citation": (
        "Carter, J., Chen, X., Cazzola, D., Trewartha, G., Preatoni, E. (2024). Full Body Kinematics and Ground "
        "Reaction Forces of Fifty Heterogeneous Runners Completing Treadmill Running at Various Speeds and Gradients. "
        "Bath: University of Bath Research Data Archive."
    ),
    "doi": "10.15125/BATH-01341",
    "url": "https://researchdata.bath.ac.uk/1341/",
    "license": "CC BY 4.0",
    "license_url": "https://creativecommons.org/licenses/by/4.0/",
    "license_file": "myo_sim/models/markersets/LICENSE-BATH-RUNNING.txt",
    "files_used": "P###.zip: P###/P###_Static_1.c3d (static standing trial of each participant)",
}

# segment: (body without side suffix, basis markers on model landmark sites, fitted markers with their body if it differs)
SEGMENTS = {
    "thigh": ("femur", ["FLE", "FME", "FAL", "TAM"], ["TH1", "TH2", "TH3", "TH4", "FT"]),
    "shank": ("tibia", ["FAL", "TAM", "FLE"], ["SK1", "SK2", "SK3", "SK4"]),
    "foot": ("calcn", ["CAL", "5MTP", "FAL", "TAM"], ["HAL", "B5MTP", "PT", "FT1", "FT2", "FT3", "FT4", "FT5", "1MTP", "B1MTP", "ST"]),
}  # fmt: skip
BODY_OVERRIDE = {"ST": "talus"}

# marker type and placement (from the dataset's MarkerSet_Info.docx); {side} becomes "right" or "left"
DESCRIPTION = {
    "TH1": "cluster; thigh cluster marker 1, {side}",
    "TH2": "cluster; thigh cluster marker 2, {side}",
    "TH3": "cluster; thigh cluster marker 3, {side}",
    "TH4": "cluster; thigh cluster marker 4, {side}",
    "FT": "anatomical; greater trochanter of the femur, {side} (static trial)",
    "SK1": "cluster; shank cluster marker 1, {side}",
    "SK2": "cluster; shank cluster marker 2, {side}",
    "SK3": "cluster; shank cluster marker 3, {side}",
    "SK4": "cluster; shank cluster marker 4, {side}",
    "ST": "anatomical; subtalar joint, {side} (static trial)",
    "HAL": "anatomical; hallux, {side}",
    "B5MTP": "anatomical; base of the fifth metatarsal, {side}",
    "PT": "anatomical; peroneal tubercle, {side}",
    "FT1": "technical; foot tracking marker 1 (toe box or midfoot), {side}",
    "FT2": "technical; foot tracking marker 2 (toe box or midfoot), {side}",
    "FT3": "technical; foot tracking marker 3 (toe box or midfoot), {side}",
    "FT4": "technical; foot tracking marker 4 (toe box or midfoot), {side}",
    "FT5": "technical; foot tracking marker 5, between heel and peroneal tubercle, {side}",
    "1MTP": "anatomical; first metatarsophalangeal joint, {side} (static trial)",
    "B1MTP": "anatomical; base of the first metatarsal, {side} (static trial)",
}
SIDES = {"R": ("_r", "right"), "L": ("_l", "left")}


# ---------------------------------------------------------------- reading the published trials


def _read_c3d(path: Path) -> tuple[list[str], np.ndarray]:
    """Marker labels and the mean position (m) of each marker over the first ``N_FRAMES`` frames."""
    try:
        import ezc3d
    except ImportError as err:
        raise SystemExit("reading the Bath C3D files needs ezc3d: pip install ezc3d") from err
    c3d = ezc3d.c3d(str(path))
    point = c3d["parameters"]["POINT"]
    labels = [s.strip() for s in point["LABELS"]["value"]]
    unit = point["UNITS"]["value"][0].strip().lower()
    scale = {"mm": 1e-3, "cm": 1e-2, "m": 1.0}[unit]
    xyz = c3d["data"]["points"][:3, :, :N_FRAMES].astype(float) * scale  # (3, markers, frames)
    xyz[:, np.all(xyz == 0.0, axis=0)] = np.nan  # (0, 0, 0) marks a gap in C3D
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)  # all-gap markers give NaN
        mean = np.nanmean(xyz, axis=2).T
    return labels, mean


def static_trials(data_dir: Path) -> Iterator[tuple[str, list[str], np.ndarray]]:
    """Yield (participant, labels, mean marker positions) for every static trial in the download directory."""
    found = {}
    for z in sorted(data_dir.glob("P[0-9][0-9][0-9].zip")):
        found.setdefault(z.stem, z)
    for d in sorted(data_dir.glob("P[0-9][0-9][0-9]/P[0-9][0-9][0-9]_Static_1.c3d")):
        found.setdefault(d.parent.name, d)
    if not found:
        raise SystemExit(f"no P###.zip or P###/P###_Static_1.c3d in {data_dir}")
    for participant, path in sorted(found.items()):
        if path.suffix == ".c3d":
            yield participant, *_read_c3d(path)
            continue
        with zipfile.ZipFile(path) as zf:
            member = next((n for n in zf.namelist() if re.search(rf"{participant}_Static_1\.c3d$", n, re.I)), None)
            if member is None:
                print(f"skipping {path.name}: no static trial", file=sys.stderr)
                continue
            with tempfile.TemporaryDirectory() as tmp:
                target = Path(tmp) / "static.c3d"
                target.write_bytes(zf.read(member))
                yield participant, *_read_c3d(target)


# ---------------------------------------------------------------- fitting


def similarity(model_pts: np.ndarray, data_pts: np.ndarray):
    """Least-squares similarity transform (scale, rotation, translation) mapping data points onto model points."""
    ca, cb = model_pts.mean(0), data_pts.mean(0)
    u, s, vt = np.linalg.svd((data_pts - cb).T @ (model_pts - ca))
    d = np.diag([1.0, 1.0, np.sign(np.linalg.det(u @ vt))])
    rot = (u @ d @ vt).T
    scale = (s * np.diag(d)).sum() / ((data_pts - cb) ** 2).sum()
    return lambda x: scale * (x - cb) @ rot.T + ca


def model_reference() -> tuple[mujoco.MjModel, mujoco.MjData, float]:
    """Model at its default pose with the marker set added, and the world x of its sagittal plane."""
    spec = myo_sim.load_spec(MODEL)
    add_markerset(spec, "bath_running")
    model = spec.compile()
    data = mujoco.MjData(model)
    mujoco.mj_forward(model, data)
    midline = float(data.xpos[model.body("pelvis").id][0])
    return model, data, midline


def fit(data_dir: Path) -> dict:
    """Fit all generated markers to the static trials; returns the provenance record."""
    model, data, midline = model_reference()
    site = {model.site(i).name: data.site_xpos[i].copy() for i in range(model.nsite)}
    mirror = np.array([-1.0, 1.0, 1.0])
    offset = np.array([2.0 * midline, 0.0, 0.0])

    mapped: dict[str, list[np.ndarray]] = {}
    subjects: dict[str, set[str]] = {}
    residuals: dict[str, list[float]] = {seg: [] for seg in SEGMENTS}
    participants = []
    for participant, labels, xyz in static_trials(data_dir):
        participants.append(participant)
        index = {k: i for i, k in enumerate(labels) if np.isfinite(xyz[i]).all()}
        for seg, (_, basis, targets) in SEGMENTS.items():
            for side in "RL":
                names = [side + k for k in basis if side + k in index]
                if len(names) < 3:
                    continue
                model_pts = np.array([site[k] for k in names])
                transform = similarity(model_pts, np.array([xyz[index[k]] for k in names]))
                err = transform(np.array([xyz[index[k]] for k in names])) - model_pts
                residuals[seg].append(float(np.sqrt((err**2).sum(1).mean())))
                for t in targets:
                    if side + t not in index:
                        continue
                    p = transform(xyz[index[side + t]][None])[0]
                    if side == "L":
                        p = p * mirror + offset  # mirror onto the right side
                    mapped.setdefault(t, []).append(p)
                    subjects.setdefault(t, set()).add(participant)

    markers = {}
    for seg, (body, _, targets) in SEGMENTS.items():
        for t in targets:
            pts = np.array(mapped[t])
            median = np.median(pts, axis=0)
            spread = float(np.median(np.linalg.norm(pts - median, axis=1)))
            for side, (suffix, word) in SIDES.items():
                world = median if side == "R" else median * mirror + offset
                bname = BODY_OVERRIDE.get(t, body) + suffix
                bid = model.body(bname).id
                local = data.xmat[bid].reshape(3, 3).T @ (world - data.xpos[bid])
                markers[side + t] = {
                    "body": bname,
                    "pos": [round(float(v), DECIMALS) + 0.0 for v in local],
                    "segment": seg,
                    "description": DESCRIPTION[t].format(side=word),
                    "n_samples": len(pts),
                    "n_subjects": len(subjects[t]),
                    "spread_mm": round(1e3 * spread, 1),
                }
    return {
        "topic": "Bath running marker set: positions of the fitted markers in myofullbody",
        "source": SOURCE,
        "generator": GENERATOR,
        "method": (
            f"Mean of the first {N_FRAMES} frames of each participant's static standing trial; per segment and side, "
            "a least-squares similarity transform maps the anatomical basis markers onto their model landmark sites "
            f"({MODEL}, default pose) and carries the other markers into the model; left sides are mirrored about "
            "the pelvis sagittal plane; median over participants and sides; positions in the body frame "
            f"(x anterior, y up, z right), rounded to {DECIMALS} decimals. Modified from the source: the values are "
            "derived, not recorded positions."
        ),
        "units": {"pos": "m", "spread_mm": "mm (median distance of the mapped samples from the median)",
                  "fit_rms_mm": "mm (RMS distance of the basis markers after the similarity fit, in model scale)"},
        "n_subjects": len(participants),
        "frames_per_trial": N_FRAMES,
        "segments": {
            seg: {
                "basis": basis,
                "n_fits": len(residuals[seg]),
                "fit_rms_mm": {
                    "median": round(1e3 * float(np.median(residuals[seg])), 1),
                    "max": round(1e3 * float(np.max(residuals[seg])), 1),
                },
            }
            for seg, (_, basis, _) in SEGMENTS.items()
        },
        "markers": markers,
    }  # fmt: skip


# ---------------------------------------------------------------- writing the generated blocks


def _fmt(v: float) -> str:
    return f"{round(v, DECIMALS) + 0.0:g}"


def render_blocks(record: dict) -> dict[str, list[str]]:
    """Site lines of each generated block, keyed by body name, in the order of ``SEGMENTS``."""
    blocks: dict[str, list[str]] = {}
    for name, m in record["markers"].items():
        pos = " ".join(_fmt(v) for v in m["pos"])
        line = f'      <site name="{name}" class="myomarker_fitted" pos="{pos}"/>  <!-- {m["description"]} -->'
        blocks.setdefault(m["body"], []).append(line)
    return blocks


def read_blocks(text: str) -> dict[str, list[str]]:
    """Site lines of each generated block in the overlay XML, keyed by the enclosing body name."""
    blocks = {}
    for match in re.finditer(rf"{re.escape(BEGIN)}\n(.*?)\n\s*{re.escape(END)}", text, re.S):
        body = re.findall(r'<body name="(\w+)">', text[: match.start()])[-1]
        blocks[body] = match.group(1).split("\n")
    return blocks


def write_blocks(text: str, record: dict) -> str:
    """Overlay XML with every generated block replaced by the values of ``record``."""
    blocks = render_blocks(record)
    if set(blocks) != set(read_blocks(text)):
        raise ValueError(f"generated blocks {sorted(read_blocks(text))} do not match bodies {sorted(blocks)}")

    def replace(match: re.Match) -> str:
        body = re.findall(r'<body name="(\w+)">', text[: match.start()])[-1]
        return "\n".join([match.group(1) + BEGIN, *blocks[body], match.group(2) + END])

    return re.sub(rf"([ \t]*){re.escape(BEGIN)}\n.*?\n([ \t]*){re.escape(END)}", replace, text, flags=re.S)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("data_dir", type=Path, help="directory with the downloaded P###.zip files (or extracted P###/)")
    parser.add_argument("--check", action="store_true", help="compare with the committed values instead of writing")
    args = parser.parse_args()

    record = fit(args.data_dir)
    committed = json.loads(JSON_PATH.read_text()) if JSON_PATH.exists() else None
    old = {k: np.array(v["pos"]) for k, v in (committed or {}).get("markers", {}).items()}
    if not old:  # first run: compare with the XML
        old = {n: np.array([float(x) for x in re.search(r'pos="([^"]+)"', ln).group(1).split()])
               for lines in read_blocks(XML_PATH.read_text()).values() for ln in lines
               for n in re.findall(r'name="(\w+)"', ln)}  # fmt: skip
    diff = {k: 1e3 * float(np.linalg.norm(np.array(m["pos"]) - old[k])) for k, m in record["markers"].items() if k in old}
    worst = max(diff, key=diff.get)
    print(f"{record['n_subjects']} participants; max difference to the committed positions {diff[worst]:.2f} mm ({worst})")
    for seg, info in record["segments"].items():
        print(f"  {seg}: {info['n_fits']} fits, basis RMS median {info['fit_rms_mm']['median']} mm")
    if args.check:
        sys.exit(0 if diff[worst] < 0.15 else 1)  # rounding to 0.1 mm
    XML_PATH.write_text(write_blocks(XML_PATH.read_text(), record))
    JSON_PATH.parent.mkdir(parents=True, exist_ok=True)
    JSON_PATH.write_text(json.dumps(record, indent=2) + "\n")
    print(f"wrote {XML_PATH.relative_to(ROOT.parent)} and {JSON_PATH.relative_to(ROOT.parent)}")


if __name__ == "__main__":
    main()
