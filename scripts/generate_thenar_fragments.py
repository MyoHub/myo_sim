"""Write the thenar tendon and muscle fragments from ``build/data/thenar_muscles.json``.

The attachment sites live in ``myoarm_r_chain.xml``. This script writes
``myoarm_r_thenar_tendon.xml`` (straight paths through those sites) and
``myoarm_r_thenar_muscle.xml`` (peak force and length range from the table's
architecture). The length range is a rigid tendon of slack length
``(L_MT(q = 0) - L_fo cos(alpha)) / 1.033`` (Barry et al. 2018, Eq. 1), so the
muscle class's normalised fibre-length range spans the same range of L_fo.

Run: ``uv run python scripts/generate_thenar_fragments.py`` (rewrites both files).
"""

from __future__ import annotations

from typing import Any

import mujoco
import numpy as np

from myo_sim.build.compose import RIGHT_ARM_THENAR_MUSCLES_XML, RIGHT_ARM_THENAR_TENDONS_XML, build_spec
from myo_sim.build.hand_data import load_thenar_table

MUSCLE_CLASS = "myoarm_forearm_muscle"
CLASS_REFERENCE = "OP"  # existing muscle of MUSCLE_CLASS: source of the normalised fibre-length range
HEADER = (
    "Generated by scripts/generate_thenar_fragments.py from myo_sim/build/data/thenar_muscles.json; edit those, not this file."
)


def _cite(table: dict[str, Any], key: str) -> str:
    citation = table["sources"][key]["citation"]
    return f"{citation.split()[0]} et al. {''.join(c for c in key if c.isdigit())}"


def tendon_fragment_xml(table: dict[str, Any]) -> str:
    """Text of ``myoarm_r_thenar_tendon.xml``."""
    lines = ["<mujocoinclude>", f"    <!-- {HEADER} -->", "    <tendon>"]
    for muscle in table["muscles"]:
        lines.append(
            f"        <!-- {muscle['name']} ({muscle['anatomy']}): path from {_cite(table, muscle['source'])} (MIT) -->"
        )
        lines.append(f'        <spatial name="{muscle["name"]}_tendon" class="{MUSCLE_CLASS}">')
        for i in range(1, len(muscle["sites"]) + 1):
            lines.append(f'            <site site="{muscle["name"]}-P{i}_r"/>')
        lines.append("        </spatial>")
    return "\n".join([*lines, "    </tendon>", "</mujocoinclude>", ""])


def architecture_lengthranges(table: dict[str, Any]) -> dict[str, tuple[float, float]]:
    """Length range per muscle from its straight site path at q = 0 (sites from ``myoarm_r_chain.xml``)."""
    model = build_spec("myoarm_r", thenar_muscles=False, passive_moments=False).compile()
    data = mujoco.MjData(model)
    data.qpos[:] = 0.0
    mujoco.mj_kinematics(model, data)
    lo, hi = model.actuator_gainprm[model.actuator(CLASS_REFERENCE).id, :2]
    ranges = {}
    for muscle in table["muscles"]:
        points = [data.site_xpos[model.site(f"{muscle['name']}-P{i}_r").id] for i in range(1, len(muscle["sites"]) + 1)]
        l_mt0 = float(sum(np.linalg.norm(b - a) for a, b in zip(points[:-1], points[1:])))
        l_fo = muscle["optimal_fiber_length_m"]["value"]
        l_ts = (l_mt0 - l_fo * np.cos(np.radians(muscle["pennation_deg"]["value"]))) / 1.033
        ranges[muscle["name"]] = (float(l_ts + lo * l_fo), float(l_ts + hi * l_fo))
    return ranges


def muscle_fragment_xml(table: dict[str, Any], lengthranges: dict[str, tuple[float, float]]) -> str:
    """Text of ``myoarm_r_thenar_muscle.xml``."""
    lines = ["<mujocoinclude>", f"    <!-- {HEADER} -->", "    <actuator>"]
    for muscle in table["muscles"]:
        arch = _cite(table, muscle["architecture_source"])
        lines.append(
            f"        <!-- {muscle['name']}: force {muscle['force_N']['derivation']}, L_fo"
            f" {muscle['optimal_fiber_length_m']['value']} m, pennation {muscle['pennation_deg']['value']} deg ({arch});"
            " lengthrange from the rigid-tendon slack length of Barry et al. 2018 Eq. 1 -->"
        )
        lo, hi = lengthranges[muscle["name"]]
        lines.append(
            f'        <muscle name="{muscle["name"]}" force="{muscle["force_N"]["value"]:g}" class="{MUSCLE_CLASS}"'
            f' tendon="{muscle["name"]}_tendon" lengthrange="{lo!r} {hi!r}"/>'
        )
    return "\n".join([*lines, "    </actuator>", "</mujocoinclude>", ""])


def main() -> None:
    table = load_thenar_table()
    ranges = architecture_lengthranges(table)
    RIGHT_ARM_THENAR_TENDONS_XML.write_text(tendon_fragment_xml(table))
    RIGHT_ARM_THENAR_MUSCLES_XML.write_text(muscle_fragment_xml(table, ranges))
    for name, (lo, hi) in ranges.items():
        print(f"{name}: lengthrange {lo!r} {hi!r}")


if __name__ == "__main__":
    main()
