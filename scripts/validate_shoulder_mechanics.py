def write_wiki(result: dict[str, Any]) -> None:
    text = WIKI.read_text()
    block = wiki_block(result)
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        raise SystemExit(f"{WIKI} has no generated block; add the markers first")
    WIKI.write_text(text)


