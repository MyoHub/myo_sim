class Arm:
    """``myoarm_r`` with helpers to place the humerus at humerothoracic angles."""

    def __init__(self) -> None:
        self.model = m = myo_sim.load_spec("myoarm_r").compile()
        self.data = mujoco.MjData(m)
        self.couplings = JointCouplings.from_model(m)
        self.axes = [m.jnt_axis[m.joint(j).id] for j in ("elv_angle_r", "shoulder_elv_r", "shoulder_rot_r")]
        self.qadr = {
            j: m.jnt_qposadr[m.joint(j).id] for j in ("elv_angle_r", "shoulder_elv_r", "shoulder_rot_r", "elbow_flexion_r")
        }
        self.gh_dof = [m.jnt_dofadr[m.joint(j).id] for j in fss.GH]
        self.chest, self.humerus = m.body("chest_r").id, m.body("humerus_r").id
        self.peak = m.actuator_gainprm[:, 2].copy()

    def humerothoracic(self, plane: float, elevation: float, rotation: float) -> np.ndarray:
        """Humerus orientation in ``chest_r`` (deg; rotation positive internal), as in ``fit_shoulder_strength``."""
        ay, ax, ar = self.axes
        p, e, r = np.radians([plane, elevation, rotation])
        return fss.axis_rot(ay, p) @ fss.axis_rot(ax, e) @ fss.axis_rot(ay, -p) @ fss.axis_rot(ar, r)

    def _hum_in_chest(self, qpos: np.ndarray) -> np.ndarray:
        m, d = self.model, self.data
        d.qpos[:] = qpos
        mujoco.mj_kinematics(m, d)
        return d.xmat[self.chest].reshape(3, 3).T @ d.xmat[self.humerus].reshape(3, 3)

    def qpos(self, plane: float, elevation: float, rotation: float, elbow: float, girdle: dict[str, list[float]]) -> np.ndarray:
        """qpos with the girdle at *girdle* and the glenohumeral angles that put the humerus at the target."""
        m = self.model
        base = m.qpos0.copy()
        for name, values in girdle.items():
            a = m.jnt_qposadr[m.joint(name).id]
            base[a : a + len(values)] = values
        base[self.qadr["elbow_flexion_r"]] = np.radians(elbow)
        target = self.humerothoracic(plane, elevation, rotation)

        def build(x: np.ndarray) -> np.ndarray:
            q = base.copy()
            q[[self.qadr["elv_angle_r"], self.qadr["shoulder_elv_r"], self.qadr["shoulder_rot_r"]]] = x
            project_joint_couplings(self.couplings, q)
            return q

        def residual(x: np.ndarray) -> np.ndarray:
            return Rotation.from_matrix(target.T @ self._hum_in_chest(build(x))).as_rotvec()

        x0 = np.radians([plane, elevation, rotation])
        best = min(
            (least_squares(residual, s, xtol=1e-14, ftol=1e-14) for s in (x0, x0 + [0.3, 0, 0], x0 - [0.3, 0, 0.3])),
            key=lambda s: s.cost,
        )
        if best.cost > 1e-12:
            raise RuntimeError(f"humerus not placed at {plane, elevation, rotation}: cost {best.cost}")
        return build(best.x)

    def moment_arms(self, qpos: np.ndarray, u_chest: np.ndarray, h: float = 1e-4) -> np.ndarray:
        """-dL/dtheta (m) of every actuator for a humerus rotation about chest axis *u*; girdle and elbow frozen."""
        m, d = self.model, self.data
        d.qpos[:] = qpos
        mujoco.mj_kinematics(m, d)
        mujoco.mj_comPos(m, d)
        jp, jr = np.zeros((3, m.nv)), np.zeros((3, m.nv))
        mujoco.mj_jacBody(m, d, jp, jr, self.humerus)
        u = d.xmat[self.chest].reshape(3, 3) @ u_chest
        dq = np.linalg.lstsq(jr[:, self.gh_dof], u, rcond=None)[0]
        lengths = []
        for s in (1.0, -1.0):
            q = qpos.copy()
            for dof, v in zip(self.gh_dof, dq):
                q[m.jnt_qposadr[m.dof_jntid[dof]]] += s * h * v
            d.qpos[:] = q
            mujoco.mj_kinematics(m, d)
            mujoco.mj_comPos(m, d)
            mujoco.mj_tendon(m, d)
            mujoco.mj_transmission(m, d)
            lengths.append(d.actuator_length.copy())
        return -(lengths[0] - lengths[1]) / (2 * h)

    def axis(self, f: Any, h: float = 1e-6) -> np.ndarray:
        return Rotation.from_matrix(f(h) @ f(-h).T).as_rotvec() / (2 * h)

    def combined(self, arms: np.ndarray, muscles: tuple[str, ...]) -> float:
        ids = [self.model.actuator(f"{n}_r").id for n in muscles]
        return float(np.sum(arms[ids] * self.peak[ids]) / np.sum(self.peak[ids]))


def moment_arm_curves(arm: Arm) -> dict[str, dict[str, list[float]]]:
    """Model moment arms (mm) per plane and literature muscle; girdle at rest, elbow 90 deg."""
    out: dict[str, dict[str, list[float]]] = {}
    for plane, p in PLANES.items():
        rows: dict[str, list[float]] = {k: [] for k in MUSCLES}
        for e in ELEV:
            q = arm.qpos(p, e, 0.0, 90.0, {})
            u = arm.axis(lambda x, p=p, e=e: arm.humerothoracic(p, e + np.degrees(x), 0.0))
            arms = arm.moment_arms(q, u)
            for k, muscles in MUSCLES.items():
                rows[k].append(round(1e3 * arm.combined(arms, muscles), 2))
        out[plane] = rows
    rows = {k: [] for k in MUSCLES}
    for r in ROT:
        q = arm.qpos(0.0, 0.0, -r, 90.0, {})
        u = arm.axis(lambda x, r=r: arm.humerothoracic(0.0, 0.0, -r - np.degrees(x)))  # + = external rotation
        arms = arm.moment_arms(q, u)
        for k, muscles in MUSCLES.items():
            rows[k].append(round(1e3 * arm.combined(arms, muscles), 2))
    out["rotation"] = rows
    return out


def path_fitted() -> set[tuple[str, str]]:
    """(plane, muscle) curves that ``fit_shoulder_paths.py`` used to place path sites; they are no longer held out."""
    if not PATHS.exists():
        return set()
    out = set()
    for d in json.loads(PATHS.read_text())["designs"]:
        for plane in d.get("planes", ("coronal", "scaption", "flexion", "rotation")):
            out.add((plane, d["muscle"]))
    return out


def compare_moment_arms(model: dict[str, dict[str, list[float]]]) -> dict[str, Any]:
    """Per plane and muscle: the band over the studies at each angle, the model's excess outside it."""
    fitted = path_fitted()
    rows = []
    for plane, studies in LIT_CURVES.items():
        grid = ROT if plane == "rotation" else ELEV
        for muscle in MUSCLES:
            curves = {s: v[muscle] for s, v in studies.items() if muscle in v}
            if not curves:
                continue
            lo, hi, excess = [], [], []
            for i, angle in enumerate(grid):
                vals = [c[i] for c in curves.values() if i < len(c)]
                if not vals:
                    continue
                a, b = min(vals), max(vals)
                x = model[plane][muscle][i]
                lo.append(a)
                hi.append(b)
                excess.append(round(max(a - x, x - b, 0.0), 2))
            n = len(excess)
            rows.append(
                {
                    "plane": plane,
                    "muscle": muscle,
                    "angles_deg": list(grid[:n]),
                    "studies": sorted(curves),
                    "model_mm": model[plane][muscle][:n],
                    "band_lo_mm": lo,
                    "band_hi_mm": hi,
                    "in_band": sum(e == 0 for e in excess),
                    "within_5mm": sum(e <= 5 for e in excess),
                    "n": n,
                    "max_excess_mm": max(excess),
                    "path_fitted": (plane, muscle) in fitted,
                }
            )
    gatti = {}
    i60 = ELEV.index(60)
    for muscle, (a, b) in GATTI_60.items():
        x = model["scaption"][muscle][i60]
        gatti[muscle] = {"model_mm": x, "range_mm": [a, b], "in_range": a <= x <= b}
    peaks = {}
    for (plane, muscle), lit in HIK_PEAKS.items():
        vals = np.array(model[plane][muscle])
        peaks[f"{plane}/{muscle}"] = {"model_peak_mm": float(vals[np.argmax(np.sign(lit) * vals)]), "pooled_peak_mm": lit}
    return {"curves": rows, "gatti2007_scaption_60": gatti, "hik2019_pooled_peaks": peaks}


def posture_of(trial: dict[str, Any], table: dict[str, Any]) -> dict[str, Any]:
    if "pose_of" in trial:
        (src,) = [t for t in table["targets"] if t["name"] == trial["pose_of"]]
        return src["posture"]
    return trial["posture"]


