class Arm:
    """``myoarm_r`` with helpers to place the humerus at humerothoracic angles."""

    def __init__(self) -> None:
        self.model = m = myo_sim.load_spec("myoarm_r").compile()
        self.data = mujoco.MjData(m)
        self.couplings = JointCouplings.from_model(m)
        self.axes = [m.jnt_axis[m.joint(j).id] for j in ("elv_angle_r", "shoulder_elv_r", "shoulder_rot_r")]
        self.qadr = {
            j: m.jnt_qposadr[m.joint(j).id] for j in ("elv_angle_r", "shoulder_elv_r", "shoulder_rot_r", "elbow_flexion_r")
        }
        self.gh_dof = [m.jnt_dofadr[m.joint(j).id] for j in fss.GH]
        self.chest, self.humerus = m.body("chest_r").id, m.body("humerus_r").id
        self.peak = m.actuator_gainprm[:, 2].copy()

    def humerothoracic(self, plane: float, elevation: float, rotation: float) -> np.ndarray:
        """Humerus orientation in ``chest_r`` (deg; rotation positive internal), as in ``fit_shoulder_strength``."""
        ay, ax, ar = self.axes
        p, e, r = np.radians([plane, elevation, rotation])
        return fss.axis_rot(ay, p) @ fss.axis_rot(ax, e) @ fss.axis_rot(ay, -p) @ fss.axis_rot(ar, r)

    def _hum_in_chest(self, qpos: np.ndarray) -> np.ndarray:
        m, d = self.model, self.data
        d.qpos[:] = qpos
        mujoco.mj_kinematics(m, d)
        return d.xmat[self.chest].reshape(3, 3).T @ d.xmat[self.humerus].reshape(3, 3)

    def qpos(self, plane: float, elevation: float, rotation: float, elbow: float, girdle: dict[str, list[float]]) -> np.ndarray:
        """qpos with the girdle at *girdle* and the glenohumeral angles that put the humerus at the target."""
        m = self.model
        base = m.qpos0.copy()
        for name, values in girdle.items():
            a = m.jnt_qposadr[m.joint(name).id]
            base[a : a + len(values)] = values
        base[self.qadr["elbow_flexion_r"]] = np.radians(elbow)
        target = self.humerothoracic(plane, elevation, rotation)

        def build(x: np.ndarray) -> np.ndarray:
            q = base.copy()
            q[[self.qadr["elv_angle_r"], self.qadr["shoulder_elv_r"], self.qadr["shoulder_rot_r"]]] = x
            project_joint_couplings(self.couplings, q)
            return q

        def residual(x: np.ndarray) -> np.ndarray:
            return Rotation.from_matrix(target.T @ self._hum_in_chest(build(x))).as_rotvec()

        x0 = np.radians([plane, elevation, rotation])
        best = min(
            (least_squares(residual, s, xtol=1e-14, ftol=1e-14) for s in (x0, x0 + [0.3, 0, 0], x0 - [0.3, 0, 0.3])),
            key=lambda s: s.cost,
        )
        if best.cost > 1e-12:
            raise RuntimeError(f"humerus not placed at {plane, elevation, rotation}: cost {best.cost}")
        return build(best.x)

    def moment_arms(self, qpos: np.ndarray, u_chest: np.ndarray, h: float = 1e-4) -> np.ndarray:
        """-dL/dtheta (m) of every actuator for a humerus rotation about chest axis *u*; girdle and elbow frozen."""
        m, d = self.model, self.data
        d.qpos[:] = qpos
        mujoco.mj_kinematics(m, d)
        mujoco.mj_comPos(m, d)
        jp, jr = np.zeros((3, m.nv)), np.zeros((3, m.nv))
        mujoco.mj_jacBody(m, d, jp, jr, self.humerus)
        u = d.xmat[self.chest].reshape(3, 3) @ u_chest
        dq = np.linalg.lstsq(jr[:, self.gh_dof], u, rcond=None)[0]
        lengths = []
        for s in (1.0, -1.0):
            q = qpos.copy()
            for dof, v in zip(self.gh_dof, dq):
                q[m.jnt_qposadr[m.dof_jntid[dof]]] += s * h * v
            d.qpos[:] = q
            mujoco.mj_kinematics(m, d)
            mujoco.mj_comPos(m, d)
            mujoco.mj_tendon(m, d)
            mujoco.mj_transmission(m, d)
            lengths.append(d.actuator_length.copy())
        return -(lengths[0] - lengths[1]) / (2 * h)

    def axis(self, f: Any, h: float = 1e-6) -> np.ndarray:
        return Rotation.from_matrix(f(h) @ f(-h).T).as_rotvec() / (2 * h)

    def combined(self, arms: np.ndarray, muscles: tuple[str, ...]) -> float:
        ids = [self.model.actuator(f"{n}_r").id for n in muscles]
        return float(np.sum(arms[ids] * self.peak[ids]) / np.sum(self.peak[ids]))


def moment_arm_curves(arm: Arm) -> dict[str, dict[str, list[float]]]:
    """Model moment arms (mm) per plane and literature muscle; girdle at rest, elbow 90 deg."""
    out: dict[str, dict[str, list[float]]] = {}
    for plane, p in PLANES.items():
        rows: dict[str, list[float]] = {k: [] for k in MUSCLES}
        for e in ELEV:
            q = arm.qpos(p, e, 0.0, 90.0, {})
            u = arm.axis(lambda x, p=p, e=e: arm.humerothoracic(p, e + np.degrees(x), 0.0))
            arms = arm.moment_arms(q, u)
            for k, muscles in MUSCLES.items():
                rows[k].append(round(1e3 * arm.combined(arms, muscles), 2))
        out[plane] = rows
    rows = {k: [] for k in MUSCLES}
    for r in ROT:
        q = arm.qpos(0.0, 0.0, -r, 90.0, {})
        u = arm.axis(lambda x, r=r: arm.humerothoracic(0.0, 0.0, -r - np.degrees(x)))  # + = external rotation
        arms = arm.moment_arms(q, u)
        for k, muscles in MUSCLES.items():
            rows[k].append(round(1e3 * arm.combined(arms, muscles), 2))
    out["rotation"] = rows
    return out


def path_fitted() -> set[tuple[str, str]]:
    """(plane, muscle) curves that an adopted ``fit_shoulder_paths.py`` candidate was fitted to; they are not held out."""
    if not PATHS.exists():
        return set()
    return {
        (plane, c["muscle"])
        for c in json.loads(PATHS.read_text())["candidates"]
        if c["adopted"]
        for plane in PLANES | {"rotation": 0}
    }


def langenderfer(arm: Arm) -> dict[str, Any]:
    """Rotation arms in scaption averaged over Langenderfer et al. 2006's rotation range (held out)."""
    names = sorted({m for (m, _) in LANGENDERFER_2006} | set(LANGENDERFER_2006_REGIONS))
    per: dict[int, dict[str, float]] = {}
    for e in (10, 60):
        vals: dict[str, list[float]] = {n: [] for n in names}
        for a in LANGENDERFER_ROT:
            r = LANGENDERFER_NEUTRAL_INTERNAL - a  # internal rotation in this convention
            q = arm.qpos(PLANES["scaption"], e, r, 90.0, {})
            u = arm.axis(lambda x, e=e, r=r: arm.humerothoracic(PLANES["scaption"], e, r - np.degrees(x)))  # + = external
            arms = arm.moment_arms(q, u)
            for n in names:
                if n in MUSCLES:
                    vals[n].append(1e3 * arm.combined(arms, MUSCLES[n]))
                else:
                    vals[n].append(1e3 * arms[arm.model.actuator(f"{n}_r").id])
        per[e] = {n: float(np.mean(v)) for n, v in vals.items()}
    rows = []
    for (muscle, e), lit in LANGENDERFER_2006.items():
        x = per[e][muscle]
        rows.append(
            {
                "muscle": muscle,
                "elevation_deg": e,
                "model_mm": round(x, 1),
                "measured_mm": lit,
                "within_5mm": bool(abs(x - lit) <= 5),
            }
        )
    for name, lit in LANGENDERFER_2006_REGIONS.items():
        x = (per[10][name] + per[60][name]) / 2
        rows.append(
            {
                "muscle": name,
                "elevation_deg": "10, 60",
                "model_mm": round(x, 1),
                "measured_mm": round(lit, 1),
                "within_5mm": bool(abs(x - lit) <= 5),
            }
        )
    return {"rows": rows}


def scaption_rotation(arm: Arm) -> list[dict[str, Any]]:
    """Rotation arms (+ = external) in scaption at rotation 0 against Otis 1994 and Axford 2025 (held out)."""
    rows = []
    for e in SCAPTION_ROTATION_ELEV:
        q = arm.qpos(PLANES["scaption"], e, 0.0, 90.0, {})
        u = arm.axis(lambda x, e=e: arm.humerothoracic(PLANES["scaption"], e, -np.degrees(x)))
        arms = arm.moment_arms(q, u)
        for (muscle, elev), lit in SCAPTION_ROTATION.items():
            if elev != e:
                continue
            x = 1e3 * arm.combined(arms, MUSCLES[muscle])
            for study, v in lit.items():
                rows.append({"muscle": muscle, "elevation_deg": e, "study": study, "model_mm": round(x, 1), "measured_mm": v,
                             "within_5mm": bool(abs(x - v) <= 5)})  # fmt: skip
    return rows


def leave_one_study_out(model: dict[str, dict[str, list[float]]]) -> list[dict[str, Any]]:
    """Kuechle 1997 against Ackland 2008 per curve, with the model's rms difference to each (the between-study spread is
    the tolerance where no independent curve exists: pectoralis major, latissimus dorsi, teres major)."""
    rows = []
    for plane in ("coronal", "flexion"):
        for muscle in ("pectoralis major", "latissimus dorsi", "teres major"):
            k, a = LIT_CURVES[plane]["kuechle1997"][muscle], LIT_CURVES[plane]["ackland2008"][muscle]
            n = min(len(k), len(a))
            x = np.array(model[plane][muscle][:n])
            k, a = np.array(k[:n]), np.array(a[:n])
            rms = lambda d: round(float(np.sqrt(np.mean(d**2))), 1)  # noqa: E731
            rows.append(
                {
                    "plane": plane,
                    "muscle": muscle,
                    "angles_deg": list(ELEV[:n]),
                    "kuechle_vs_ackland_rms_mm": rms(k - a),
                    "model_vs_kuechle_rms_mm": rms(x - k),
                    "model_vs_ackland_rms_mm": rms(x - a),
                }
            )
    return rows


def compare_moment_arms(model: dict[str, dict[str, list[float]]]) -> dict[str, Any]:
    """Per plane, muscle and study set: the band over the studies at each angle, the model's excess outside it."""
    fitted = path_fitted()
    rows = []
    for plane, studies in LIT_CURVES.items():
        grid = ROT if plane == "rotation" else ELEV
        for muscle in MUSCLES:
            for subset in ("fit set", "held out"):
                curves = {s: v[muscle] for s, v in studies.items() if muscle in v and (s in FIT_SET) == (subset == "fit set")}
                if not curves:
                    continue
                lo, hi, excess = [], [], []
                for i, angle in enumerate(grid):
                    vals = [float(v) for c in curves.values() if i < len(c) for v in np.atleast_1d(c[i])]
                    if not vals:
                        continue
                    a, b = min(vals), max(vals)
                    x = model[plane][muscle][i]
                    lo.append(a)
                    hi.append(b)
                    excess.append(round(max(a - x, x - b, 0.0), 2))
                n = len(excess)
                rows.append(
                    {
                        "plane": plane,
                        "muscle": muscle,
                        "set": subset,
                        "angles_deg": list(grid[:n]),
                        "studies": sorted(curves),
                        "model_mm": model[plane][muscle][:n],
                        "band_lo_mm": lo,
                        "band_hi_mm": hi,
                        "in_band": sum(e == 0 for e in excess),
                        "within_5mm": sum(e <= 5 for e in excess),
                        "n": n,
                        "max_excess_mm": max(excess),
                        "path_fitted": subset == "fit set" and (plane, muscle) in fitted,
                    }
                )
    gatti = {}
    i60 = ELEV.index(60)
    for muscle, (a, b) in GATTI_60.items():
        x = model["scaption"][muscle][i60]
        gatti[muscle] = {"model_mm": x, "range_mm": [a, b], "in_range": a <= x <= b}
    peaks = {}
    for (plane, muscle), lit in HIK_PEAKS.items():
        vals = np.array(model[plane][muscle])
        peaks[f"{plane}/{muscle}"] = {"model_peak_mm": float(vals[np.argmax(np.sign(lit) * vals)]), "pooled_peak_mm": lit}
    return {"curves": rows, "gatti2007_scaption_60": gatti, "hik2019_pooled_peaks": peaks}


def held_out(result: dict[str, Any]) -> dict[str, Any]:
    """Summary of the checks held out from the path fit (and the fit-set curves for comparison)."""
    ma = result["moment_arms"]

    def counts(rows: list[dict[str, Any]]) -> dict[str, int]:
        return {k: int(sum(r[k] for r in rows)) for k in ("in_band", "within_5mm", "n")}

    peaks = ma["hik2019_pooled_peaks"].values()
    with_sd = [r for r in result["strength"] if r.get("sd_Nm")]
    return {
        "fit_set_curves": counts([r for r in ma["curves"] if r["set"] == "fit set"]),
        "curves": counts([r for r in ma["curves"] if r["set"] == "held out"]),
        "gatti_in_range": int(sum(v["in_range"] for v in ma["gatti2007_scaption_60"].values())),
        "gatti_n": len(ma["gatti2007_scaption_60"]),
        "langenderfer_within_5mm": int(sum(r["within_5mm"] for r in ma["langenderfer2006"]["rows"])),
        "langenderfer_n": len(ma["langenderfer2006"]["rows"]),
        "scaption_rotation_within_5mm": int(sum(r["within_5mm"] for r in ma["scaption_rotation"])),
        "scaption_rotation_n": len(ma["scaption_rotation"]),
        "peaks_within_4mm": int(sum(abs(v["model_peak_mm"] - v["pooled_peak_mm"]) <= 4.0 for v in peaks)),
        "peaks_n": len(peaks),
        "strength_within_1p5sd": int(sum(abs(r["z"]) <= 1.5 for r in with_sd)),
        "strength_with_sd": len(with_sd),
    }


def posture_of(trial: dict[str, Any], table: dict[str, Any]) -> dict[str, Any]:
    if "pose_of" in trial:
        (src,) = [t for t in table["targets"] if t["name"] == trial["pose_of"]]
        return src["posture"]
    return trial["posture"]


def strength(arm: Arm, table: dict[str, Any], poses: dict[str, dict[str, list[float]]]) -> list[dict[str, Any]]:
    """MVC moment of every trial with the public probe, and the ball-joint rig of the fit for comparison."""
    rig = fss.Rig()
    sigma = table["fit"]["result"]["value_N_per_cm2"]
    out = []
    for trial in STRENGTH:
        p = posture_of(trial, table)
        girdle = poses[trial["name"]]
        q = arm.qpos(p["plane_deg"], p["elevation_deg"], p["rotation_deg"], p["elbow_deg"], girdle)
        joint, sign = PROBE[trial["direction"]]
        active, passive, joints = max_torque_terms(arm.model, MaxTorqueMeasurement(joint, q, 1.0, sign))
        value = float(np.clip(active, 0.0, None).sum() + passive.sum() + joints)
        thorax = fss.model_moment(
            table, rig.moments_per_newton({"posture": p, "direction": trial["direction"]}, girdle), rig, sigma
        )
        row = {
            "name": trial["name"],
            "source": trial["source"],
            "fit": trial["fit"],
            "posture": {k: p[k] for k in ("plane_deg", "elevation_deg", "rotation_deg", "elbow_deg")},
            "direction": trial["direction"],
            "mean_Nm": trial["mean_Nm"],
            "sd_Nm": trial.get("sd_Nm"),
            "model_Nm": round(value, 1),
            "model_thorax_axis_Nm": round(thorax, 1),
        }
        if trial.get("sd_Nm"):
            row["z"] = round((value - trial["mean_Nm"]) / trial["sd_Nm"], 2)
        else:
            row["ratio"] = round(value / trial["mean_Nm"], 2)
        out.append(row)
    return out


def girdle_poses(table: dict[str, Any], zip_path: Path | None, previous: dict[str, Any]) -> dict[str, dict[str, list[float]]]:
    poses = {}
    missing = []
    for trial in STRENGTH:
        if "pose_of" in trial:
            poses[trial["name"]] = table["girdle_poses"][trial["pose_of"]]
        elif trial["name"] in previous:
            poses[trial["name"]] = previous[trial["name"]]
        else:
            missing.append(trial)
    if missing or zip_path:
        if zip_path is None:
            raise SystemExit(f"girdle poses missing for {[t['name'] for t in missing]}: pass --zip")
        extra = [{"name": t["name"], "posture": t["posture"]} for t in STRENGTH if "posture" in t]
        with zipfile.ZipFile(zip_path) as zf:
            poses |= fss.girdle_poses({"targets": extra}, zf)
    return poses


