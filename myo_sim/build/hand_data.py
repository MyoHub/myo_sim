"""Data behind the hand intrinsic muscles and passive joint moments of the arm.

The model is the XML: generated blocks in ``myoarm_r_tendon.xml`` and
``myoarm_r_muscle.xml`` written from the JSON tables in ``data/`` (provenance
and fitting input) by ``scripts/generate_hand_intrinsic_muscles.py`` and
``scripts/fit_passive_moments.py``. This module reads the tables, names the
passive tendons, reads and rewrites the generated blocks and evaluates the
reference passive moment of a table row.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import numpy as np

DATA_DIR = Path(__file__).with_name("data")
PASSIVE_DATA_PATH = DATA_DIR / "passive_joint_moments.json"
INTRINSIC_DATA_PATH = DATA_DIR / "hand_intrinsic_muscles.json"
PASSIVE_TENDON_PREFIX = "passive_"
APPLIED_STATUSES = ("measured", "assumed")
SPRING_FAR = 1.0e3  # rad: "no bound" side of a one-sided deadband
_INDENT = "        "


def _markers(script: str, label: str | None = None) -> tuple[str, str]:
    tag = f"scripts/{script}" + (f" ({label})" if label else "")
    return (
        f"{_INDENT}<!-- BEGIN generated by {tag}; do not edit by hand -->\n",
        f"{_INDENT}<!-- END generated by {tag} -->\n",
    )


def read_generated_block(path: Path, script: str, label: str | None = None) -> str | None:
    """Text between the BEGIN/END markers of *script* (block *label*) in *path*, or None without a block."""
    begin, end = _markers(script, label)
    text = path.read_text()
    if begin not in text:
        return None
    return text.split(begin, 1)[1].split(end, 1)[0]


def write_generated_block(path: Path, script: str, block: str, closing_tag: str, label: str | None = None) -> None:
    """Replace the generated block of *script* in *path* with *block*.

    The unlabelled block is inserted before *closing_tag* if absent. A labelled block keeps an element in
    place among hand-written ones (its index stays), so its markers must already be in the file.
    """
    begin, end = _markers(script, label)
    text = path.read_text()
    if begin in text:
        head, rest = text.split(begin, 1)
        tail = rest.split(end, 1)[1]
    elif label is not None:
        raise ValueError(f"{path.name}: no generated block {label!r} of {script}; add its markers first")
    else:
        index = text.rindex(f"    {closing_tag}")
        head, tail = text[:index], text[index:]
    path.write_text(head + begin + block + end + tail)


def load_passive_moment_table(path: Path | str | None = None) -> dict[str, Any]:
    """Read the passive-moment table (default: the packaged one)."""
    return json.loads(Path(path or PASSIVE_DATA_PATH).read_text())


def load_intrinsic_table(path: Path | str | None = None) -> dict[str, Any]:
    """Read the hand intrinsic-muscle table (default: the packaged one)."""
    return json.loads(Path(path or INTRINSIC_DATA_PATH).read_text())


def rows_with_status(table: dict[str, Any], statuses: tuple[str, ...] = ("measured",)) -> list[dict[str, Any]]:
    """Rows of the passive-moment table whose status is in *statuses*."""
    return [row for row in table["joints"] if row["status"] in statuses]


def spring_segments(row: dict[str, Any], direction: str) -> list[dict[str, Any]]:
    """Spring segments of one side of a row: a dict or a list of dicts (stacked onsets)."""
    part = row.get(direction)
    if part is None:
        return []
    return part if isinstance(part, list) else [part]


def passive_tendon_name(row: str, direction: str, index: int = 0) -> str:
    """Right-side name of the fixed tendon of segment *index* of *row*'s *direction* side."""
    return f"{PASSIVE_TENDON_PREFIX}{row}_{direction[:3]}{index or ''}_r"


def spring_parameters(direction: str, onset: float, stiffness: list[float]) -> tuple[list[float], list[float]]:
    """``(springlength, stiffness)`` of a one-sided fixed tendon acting beyond *onset*.

    MuJoCo's deadband spring ``tendon_lengthspring`` with polynomial
    ``stiffness`` gives the restoring moment ``-(k0 x + k1 x^2 + k2 x^3)``.
    """
    k0, k1, k2 = stiffness
    if direction == "positive":
        return [-SPRING_FAR, onset], [k0, k1, k2]
    # Acts below onset (x < 0): the even term flips sign to stay restoring.
    return [onset, SPRING_FAR], [k0, -k1, k2]


def passive_moment(row: dict[str, Any], q: np.ndarray | float) -> np.ndarray:
    """Reference moment (Nm) of one table row at joint angles *q* (rad)."""
    q = np.asarray(q, dtype=float)
    moment = np.zeros_like(q)
    for direction, sign in (("positive", 1.0), ("negative", -1.0)):
        for part in spring_segments(row, direction):
            x = np.maximum(sign * (q - part["onset"]), 0.0)
            k0, k1, k2 = part["stiffness"]
            moment -= sign * (k0 * x + k1 * x**2 + k2 * x**3)
    return moment
